void drcbe_la64::op_save(lagoon_assembler_t &a, const uml::instruction &inst)
{
	assert(inst.size() == 4);
	assert_no_condition(inst);
	assert_no_flags(inst);

	be_parameter dstp(*this, inst.param(0), PTYPE_M);

	load_address(a, SCRATCH_REG2, uintptr_t(dstp.memory()));

	la_st_b(&a, FLAGS_REG, SCRATCH_REG2, offsetof(drcuml_machine_state, flags));

	load_address(a, SCRATCH_REG1, uintptr_t(&m_state.fmod));
	la_ld_bu(&a, SCRATCH_REG1, SCRATCH_REG1, 0);
	la_st_b(&a, SCRATCH_REG1, SCRATCH_REG2, offsetof(drcuml_machine_state, fmod));

	load_address(a, SCRATCH_REG1, uintptr_t(&m_state.exp));
	la_ld_wu(&a, SCRATCH_REG1, SCRATCH_REG1, 0);
	la_st_w(&a, SCRATCH_REG1, SCRATCH_REG2, offsetof(drcuml_machine_state, exp));

	int regoffs = offsetof(drcuml_machine_state, r);
	for (int regnum = 0; regnum < std::size(m_state.r); regnum++)
	{
		if (int_register_map[regnum] != LA_ZERO)
		{
			la_st_d(&a, int_register_map[regnum], SCRATCH_REG2, regoffs + (8 * regnum));
		}
		else
		{
			load_address(a, SCRATCH_REG1, uintptr_t(&m_state.r[regnum].d));
			la_ld_d(&a, SCRATCH_REG1, SCRATCH_REG1, 0);
			la_st_d(&a, SCRATCH_REG1, SCRATCH_REG2, regoffs + (8 * regnum));
		}
	}

	regoffs = offsetof(drcuml_machine_state, f);
	for (int regnum = 0; regnum < std::size(m_state.f); regnum++)
	{
		if (float_register_map[regnum] != LA_F0)
		{
			la_fst_d(&a, float_register_map[regnum], SCRATCH_REG2, regoffs + (8 * regnum));
		}
		else
		{
			load_address(a, SCRATCH_REG1, uintptr_t(&m_state.f[regnum].d));
			la_fld_d(&a, TEMPF_REG1, SCRATCH_REG1, 0);
			la_fst_d(&a, TEMPF_REG1, SCRATCH_REG2, regoffs + (8 * regnum));
		}
	}
}

void drcbe_la64::op_restore(lagoon_assembler_t &a, const uml::instruction &inst)
{
	assert(inst.size() == 4);
	assert_no_condition(inst);

	be_parameter srcp(*this, inst.param(0), PTYPE_M);

	load_address(a, SCRATCH_REG2, uintptr_t(srcp.memory()));

	int regoffs = offsetof(drcuml_machine_state, r);
	for (int regnum = 0; regnum < std::size(m_state.r); regnum++)
	{
		if (int_register_map[regnum] != LA_ZERO)
		{
			la_ld_d(&a, int_register_map[regnum], SCRATCH_REG2, regoffs + (8 * regnum));
		}
		else
		{
			la_ld_d(&a, SCRATCH_REG1, SCRATCH_REG2, regoffs + (8 * regnum));
			load_address(a, FUNC_SCRATCH_REG, uintptr_t(&m_state.r[regnum].d));
			la_st_d(&a, SCRATCH_REG1, FUNC_SCRATCH_REG, 0);
		}
	}

	regoffs = offsetof(drcuml_machine_state, f);
	for (int regnum = 0; regnum < std::size(m_state.f); regnum++)
	{
		if (float_register_map[regnum] != LA_F0)
		{
			la_fld_d(&a, float_register_map[regnum], SCRATCH_REG2, regoffs + (8 * regnum));
		}
		else
		{
			la_fld_d(&a, TEMPF_REG1, SCRATCH_REG2, regoffs + (8 * regnum));
			load_address(a, SCRATCH_REG1, uintptr_t(&m_state.f[regnum].d));
			la_fst_d(&a, TEMPF_REG1, SCRATCH_REG1, 0);
		}
	}

	la_ld_bu(&a, TEMP_REG1, SCRATCH_REG2, offsetof(drcuml_machine_state, fmod));
	la_andi(&a, TEMP_REG1, TEMP_REG1, 3);
	load_address(a, TEMP_REG2, uintptr_t(&m_state.fmod));
	la_st_b(&a, TEMP_REG1, TEMP_REG2, 0);

	la_ld_wu(&a, TEMP_REG1, SCRATCH_REG2, offsetof(drcuml_machine_state, exp));
	load_address(a, TEMP_REG2, uintptr_t(&m_state.exp));
	la_st_w(&a, TEMP_REG1, TEMP_REG2, 0);

	la_ld_bu(&a, FLAGS_REG, SCRATCH_REG2, offsetof(drcuml_machine_state, flags));
	la_andi(&a, FLAGS_REG, FLAGS_REG, uml::FLAGS_ALL);

	emit_sync_fcsr(a);
}


void drcbe_la64::op_load(lagoon_assembler_t &a, const uml::instruction &inst)
{
	assert(inst.size() == 4 || inst.size() == 8);
	assert_no_condition(inst);
	assert_no_flags(inst);

	be_parameter dstp(*this, inst.param(0), PTYPE_MR);
	be_parameter basep(*this, inst.param(1), PTYPE_M);
	be_parameter indp(*this, inst.param(2), PTYPE_MRI);
	const parameter &scalesizep = inst.param(3);
	assert(scalesizep.is_size_scale());
	const int size = scalesizep.size();
	const int scale = scalesizep.scale();

	const la_gpr_t dstreg = TEMP_REG3;

	auto emit_load = [&](la_gpr_t base)
	{
		if (size == SIZE_BYTE)
			la_ld_bu(&a, dstreg, base, 0);
		else if (size == SIZE_WORD)
			la_ld_hu(&a, dstreg, base, 0);
		else if (size == SIZE_DWORD)
			la_ld_wu(&a, dstreg, base, 0);
		else
			la_ld_d(&a, dstreg, base, 0);
	};

	if (indp.is_immediate())
	{
		ptrdiff_t const offset = ptrdiff_t(int32_t(uint32_t(indp.immediate()))) << scale;
		void *const memptr = reinterpret_cast<uint8_t *>(basep.memory()) + offset;
		if (size == SIZE_BYTE)
			emit_ldrb_mem(a, dstreg, memptr);
		else if (size == SIZE_WORD)
			emit_ldrh_mem(a, dstreg, memptr);
		else if (size == SIZE_DWORD)
		{
			la_gpr_t const addr = MEM_SCRATCH_REG;
			load_address(a, addr, uintptr_t(memptr));
			la_ld_wu(&a, dstreg, addr, 0);
		}
		else
		{
			emit_ldr_mem(a, dstreg, memptr);
			if (inst.size() == 4)
				zero_extend32(a, dstreg);
		}
	}
	else
	{
		load_address(a, TEMP_REG1, uintptr_t(basep.memory()));
		mov_reg_param(a, 4, TEMP_REG2, indp);
		sign_extend32(a, TEMP_REG2);
		if (scale)
			la_slli_d(&a, TEMP_REG2, TEMP_REG2, scale);
		la_add_d(&a, TEMP_REG1, TEMP_REG1, TEMP_REG2);
		emit_load(TEMP_REG1);
		if ((size == SIZE_QWORD) && (inst.size() == 4))
			zero_extend32(a, dstreg);
		else if ((size == SIZE_DWORD) && (inst.size() == 8))
			zero_extend32(a, dstreg);
	}

	mov_param_reg(a, inst.size(), dstp, dstreg);
}

void drcbe_la64::op_loads(lagoon_assembler_t &a, const uml::instruction &inst)
{
	assert(inst.size() == 4 || inst.size() == 8);
	assert_no_condition(inst);
	assert_no_flags(inst);

	be_parameter dstp(*this, inst.param(0), PTYPE_MR);
	be_parameter basep(*this, inst.param(1), PTYPE_M);
	be_parameter indp(*this, inst.param(2), PTYPE_MRI);
	const parameter &scalesizep = inst.param(3);
	assert(scalesizep.is_size_scale());
	const int size = scalesizep.size();
	const int scale = scalesizep.scale();

	const la_gpr_t dstreg = TEMP_REG3;

	auto emit_load = [&](la_gpr_t base)
	{
		if (size == SIZE_BYTE)
			la_ld_b(&a, dstreg, base, 0);
		else if (size == SIZE_WORD)
			la_ld_h(&a, dstreg, base, 0);
		else if ((size == SIZE_DWORD) && (inst.size() == 8))
			la_ld_w(&a, dstreg, base, 0);
		else if (size == SIZE_DWORD)
			la_ld_w(&a, dstreg, base, 0);
		else
			la_ld_d(&a, dstreg, base, 0);
	};

	if (indp.is_immediate())
	{
		ptrdiff_t const offset = ptrdiff_t(int32_t(uint32_t(indp.immediate()))) << scale;
		void *const memptr = reinterpret_cast<uint8_t *>(basep.memory()) + offset;
		if (size == SIZE_BYTE)
			emit_ldrsb_mem(a, dstreg, memptr);
		else if (size == SIZE_WORD)
			emit_ldrsh_mem(a, dstreg, memptr);
		else if (size == SIZE_DWORD)
		{
			emit_ldrsw_mem(a, dstreg, memptr);
			if (inst.size() == 4)
				zero_extend32(a, dstreg);
		}
		else
		{
			emit_ldr_mem(a, dstreg, memptr);
			if (inst.size() == 4)
				zero_extend32(a, dstreg);
		}
	}
	else
	{
		load_address(a, TEMP_REG1, uintptr_t(basep.memory()));
		mov_reg_param(a, 4, TEMP_REG2, indp);
		sign_extend32(a, TEMP_REG2);
		if (scale)
			la_slli_d(&a, TEMP_REG2, TEMP_REG2, scale);
		la_add_d(&a, TEMP_REG1, TEMP_REG1, TEMP_REG2);
		emit_load(TEMP_REG1);
		if ((size == SIZE_DWORD) && (inst.size() == 4))
			zero_extend32(a, dstreg);
		else if ((size == SIZE_QWORD) && (inst.size() == 4))
			zero_extend32(a, dstreg);
	}

	mov_param_reg(a, inst.size(), dstp, dstreg);
}

void drcbe_la64::op_store(lagoon_assembler_t &a, const uml::instruction &inst)
{
	assert(inst.size() == 4 || inst.size() == 8);
	assert_no_condition(inst);
	assert_no_flags(inst);

	be_parameter basep(*this, inst.param(0), PTYPE_M);
	be_parameter indp(*this, inst.param(1), PTYPE_MRI);
	be_parameter srcp(*this, inst.param(2), PTYPE_MRI);
	const parameter &scalesizep = inst.param(3);
	const int size = scalesizep.size();
	const int scale = scalesizep.scale();

	const la_gpr_t srcreg = TEMP_REG3;

	auto emit_store = [&](la_gpr_t base)
	{
		if (size == SIZE_BYTE)
			la_st_b(&a, srcreg, base, 0);
		else if (size == SIZE_WORD)
			la_st_h(&a, srcreg, base, 0);
		else if (size == SIZE_DWORD)
			la_st_w(&a, srcreg, base, 0);
		else
			la_st_d(&a, srcreg, base, 0);
	};

	mov_reg_param(a, inst.size(), srcreg, srcp);

	if (indp.is_immediate())
	{
		ptrdiff_t const offset = ptrdiff_t(int32_t(uint32_t(indp.immediate()))) << scale;
		void *const memptr = reinterpret_cast<uint8_t *>(basep.memory()) + offset;
		if (size == SIZE_BYTE)
			emit_strb_mem(a, srcreg, memptr);
		else if (size == SIZE_WORD)
			emit_strh_mem(a, srcreg, memptr);
		else
		{
			la_gpr_t const addr = MEM_SCRATCH_REG;
			load_address(a, addr, uintptr_t(memptr));
			if (size == SIZE_DWORD)
				la_st_w(&a, srcreg, addr, 0);
			else
				la_st_d(&a, srcreg, addr, 0);
		}
	}
	else
	{
		load_address(a, TEMP_REG1, uintptr_t(basep.memory()));
		mov_reg_param(a, 4, TEMP_REG2, indp);
		sign_extend32(a, TEMP_REG2);
		if (scale)
			la_slli_d(&a, TEMP_REG2, TEMP_REG2, scale);
		la_add_d(&a, TEMP_REG1, TEMP_REG1, TEMP_REG2);
		emit_store(TEMP_REG1);
	}
}


