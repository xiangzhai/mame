void drcbe_la64::get_info(drcbe_info &info) const noexcept
{
	for (info.direct_iregs = 0; info.direct_iregs < REG_I_COUNT; info.direct_iregs++)
	{
		if (int_register_map[info.direct_iregs] == LA_ZERO)
			break;
	}

	for (info.direct_fregs = 0; info.direct_fregs < REG_F_COUNT; info.direct_fregs++)
	{
		if (float_register_map[info.direct_fregs] == LA_F0)
			break;
	}
}

[[noreturn]] void drcbe_la64::end_of_block() const
{
	osd_printf_error("drcbe_la64(%s): Fell off the end of a generated code block!\n", m_device.tag());
	std::fflush(stdout);
	std::fflush(stderr);
	std::abort();
}


void drcbe_la64::op_handle(lagoon_assembler_t &a, const uml::instruction &inst)
{
	assert_no_condition(inst);
	assert_no_flags(inst);
	assert(inst.numparams() == 1);
	assert(inst.param(0).is_code_handle());

	lagoon_label_t skip = {};
	la_b(&a, la_label(&a, &skip));

	inst.param(0).handle().set_codeptr(drccodeptr(a.cursor));

	la_addi_d(&a, LA_SP, LA_SP, -16);
	la_st_d(&a, LA_RA, LA_SP, 8);
	la_st_d(&a, LA_FP, LA_SP, 0);

	la_bind(&a, &skip);
	la_label_free(&a, &skip);
}

void drcbe_la64::op_hash(lagoon_assembler_t &a, const uml::instruction &inst)
{
	assert_no_condition(inst);
	assert_no_flags(inst);
	assert(inst.numparams() == 2);
	assert(inst.param(0).is_immediate());
	assert(inst.param(1).is_immediate());

	m_hash.set_codeptr(inst.param(0).immediate(), inst.param(1).immediate(), drccodeptr(a.cursor));
}

void drcbe_la64::op_label(lagoon_assembler_t &a, const uml::instruction &inst)
{
	assert_no_condition(inst);
	assert_no_flags(inst);
	assert(inst.numparams() == 1);
	assert(inst.param(0).is_code_label());

	uint32_t const label = inst.param(0).label();
	la_bind(&a, &m_labels[label]);
}

void drcbe_la64::op_comment(lagoon_assembler_t &a, const uml::instruction &inst)
{
	assert_no_condition(inst);
	assert_no_flags(inst);
	assert(inst.numparams() == 1);
	assert(inst.param(0).is_string());
}

void drcbe_la64::op_mapvar(lagoon_assembler_t &a, const uml::instruction &inst)
{
	assert_no_condition(inst);
	assert_no_flags(inst);
	assert(inst.numparams() == 2);
	assert(inst.param(0).is_mapvar());
	assert(inst.param(1).is_immediate());

	m_map.set_value(drccodeptr(a.cursor), inst.param(0).mapvar(), inst.param(1).immediate());
}

void drcbe_la64::op_nop(lagoon_assembler_t &a, const uml::instruction &inst)
{
}

void drcbe_la64::op_break(lagoon_assembler_t &a, const uml::instruction &inst)
{
	assert(inst.size() == 4);
	assert_no_condition(inst);
	assert_no_flags(inst);

	static const char message[] = "break from drc";
	load_address(a, REG_PARAM1, uintptr_t(message));
	call_helper_addr(a, uintptr_t(&osd_break_into_debugger));
}

void drcbe_la64::op_debug(lagoon_assembler_t &a, const uml::instruction &inst)
{
	assert(inst.size() == 4);
	assert_no_condition(inst);
	assert_no_flags(inst);

	if (m_device.machine().debug_flags & DEBUG_FLAG_ENABLED)
	{
		be_parameter pcp(*this, inst.param(0), PTYPE_MRI);

		lagoon_label_t done = {};

		load_address(a, TEMP_REG1, uintptr_t(&m_device.machine().debug_flags));
		la_ld_wu(&a, TEMP_REG1, TEMP_REG1, 0);
		la_andi(&a, TEMP_REG1, TEMP_REG1, DEBUG_FLAG_CALL_HOOK);
		la_beqz(&a, TEMP_REG1, la_label(&a, &done));

		emit_sync_fcsr(a);
		load_address(a, REG_PARAM1, m_debug_cpu_instruction_hook.obj);
		mov_reg_param(a, 4, REG_PARAM2, pcp);
		call_helper_addr(a, uintptr_t(m_debug_cpu_instruction_hook.func));
		emit_sync_fcsr(a);

		la_bind(&a, &done);
		la_label_free(&a, &done);
	}
}

void drcbe_la64::op_exit(lagoon_assembler_t &a, const uml::instruction &inst)
{
	assert(inst.size() == 4);
	assert_any_condition(inst);
	assert_no_flags(inst);

	be_parameter retp(*this, inst.param(0), PTYPE_MRI);

	lagoon_label_t skip = {};
	emit_skip(a, inst.condition(), skip);

	mov_reg_param(a, 4, REG_PARAM1, retp);
	load_address(a, TEMP_REG1, uintptr_t(m_exit));
	la_jr(&a, TEMP_REG1);

	if (inst.condition() != uml::COND_ALWAYS)
	{
		la_bind(&a, &skip);
		la_label_free(&a, &skip);
	}
}

void drcbe_la64::op_hashjmp(lagoon_assembler_t &a, const uml::instruction &inst)
{
	assert(inst.size() == 4);
	assert_no_condition(inst);
	assert_no_flags(inst);

	be_parameter modep(*this, inst.param(0), PTYPE_MRI);
	be_parameter pcp(*this, inst.param(1), PTYPE_MRI);
	const parameter &exp = inst.param(2);
	assert(exp.is_code_handle());

	if (!modep.is_immediate())
		mov_reg_param(a, 4, TEMP_REG1, modep);
	if (!pcp.is_immediate())
		mov_reg_param(a, 4, TEMP_REG2, pcp);

	auto index_pc = [&]()
	{
		if (pcp.is_immediate())
		{
			uint32_t const l1val = (pcp.immediate() >> m_hash.l1shift()) & m_hash.l1mask();
			uint32_t const l2val = (pcp.immediate() >> m_hash.l2shift()) & m_hash.l2mask();

			if (l1val)
			{
				if ((l1val * 8) < 2048)
					la_addi_d(&a, SCRATCH_REG2, SCRATCH_REG2, int32_t(l1val * 8));
				else
				{
					load_imm64(a, MEM_SCRATCH_REG, uint64_t(l1val) * 8);
					la_add_d(&a, SCRATCH_REG2, SCRATCH_REG2, MEM_SCRATCH_REG);
				}
			}
			la_ld_d(&a, SCRATCH_REG2, SCRATCH_REG2, 0);

			if (l2val)
			{
				if ((l2val * 8) < 2048)
					la_addi_d(&a, SCRATCH_REG2, SCRATCH_REG2, int32_t(l2val * 8));
				else
				{
					load_imm64(a, MEM_SCRATCH_REG, uint64_t(l2val) * 8);
					la_add_d(&a, SCRATCH_REG2, SCRATCH_REG2, MEM_SCRATCH_REG);
				}
			}
			la_ld_d(&a, SCRATCH_REG2, SCRATCH_REG2, 0);
		}
		else
		{
			if (m_hash.l1bits())
			{
				la_bstrpick_d(&a, MEM_SCRATCH_REG, TEMP_REG2, m_hash.l1shift() + m_hash.l1bits() - 1, m_hash.l1shift());
				la_slli_d(&a, MEM_SCRATCH_REG, MEM_SCRATCH_REG, 3);
				la_add_d(&a, SCRATCH_REG2, SCRATCH_REG2, MEM_SCRATCH_REG);
			}
			la_ld_d(&a, SCRATCH_REG2, SCRATCH_REG2, 0);

			if (m_hash.l2bits())
			{
				la_bstrpick_d(&a, MEM_SCRATCH_REG, TEMP_REG2, m_hash.l2shift() + m_hash.l2bits() - 1, m_hash.l2shift());
				la_slli_d(&a, MEM_SCRATCH_REG, MEM_SCRATCH_REG, 3);
				la_add_d(&a, SCRATCH_REG2, SCRATCH_REG2, MEM_SCRATCH_REG);
			}
			la_ld_d(&a, SCRATCH_REG2, SCRATCH_REG2, 0);
		}
	};

	if (modep.is_immediate() && m_hash.populate_mode(modep.immediate()))
	{
		if (pcp.is_immediate() && !m_invariant_block)
		{
			uint32_t const l1val = (pcp.immediate() >> m_hash.l1shift()) & m_hash.l1mask();
			uint32_t const l2val = (pcp.immediate() >> m_hash.l2shift()) & m_hash.l2mask();
			load_address(a, SCRATCH_REG2, uintptr_t(&m_hash.base()[modep.immediate()][l1val][l2val]));
			la_ld_d(&a, SCRATCH_REG2, SCRATCH_REG2, 0);
		}
		else
		{
			load_imm64(a, SCRATCH_REG2, uintptr_t(m_hash.base()[modep.immediate()]));
			index_pc();
		}
	}
	else
	{
		load_address(a, SCRATCH_REG2, uintptr_t(m_hash.base()));

		if (modep.is_immediate())
		{
			uint64_t const offs = uint64_t(modep.immediate()) * 8;
			if (offs < 2048)
				la_addi_d(&a, SCRATCH_REG2, SCRATCH_REG2, int32_t(offs));
			else
			{
				load_imm64(a, MEM_SCRATCH_REG, offs);
				la_add_d(&a, SCRATCH_REG2, SCRATCH_REG2, MEM_SCRATCH_REG);
			}
		}
		else
		{
			la_slli_d(&a, MEM_SCRATCH_REG, TEMP_REG1, 3);
			la_add_d(&a, SCRATCH_REG2, SCRATCH_REG2, MEM_SCRATCH_REG);
		}
		la_ld_d(&a, SCRATCH_REG2, SCRATCH_REG2, 0);

		index_pc();
	}

	lagoon_label_t const target = {};
	lagoon_label_t target_label = target;
	la_la_local(&a, REG_PARAM1, la_label(&a, &target_label));
	la_jr(&a, SCRATCH_REG2);
	la_bind(&a, &target_label);

	mov_mem_param(a, 4, &m_state.exp, pcp);

	drccodeptr *const targetptr = exp.handle().codeptr_addr();
	if (*targetptr != nullptr)
	{
		load_address(a, SCRATCH_REG2, uintptr_t(*targetptr));
	}
	else
	{
		load_address(a, SCRATCH_REG2, uintptr_t(targetptr));
		la_ld_d(&a, SCRATCH_REG2, SCRATCH_REG2, 0);
	}
	la_jirl(&a, LA_RA, SCRATCH_REG2, 0);

	la_label_free(&a, &target_label);
}

