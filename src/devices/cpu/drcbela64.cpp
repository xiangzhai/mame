void drcbe_la64::op_hashjmp(lagoon_assembler_t &a, const uml::instruction &inst)
{
	assert(inst.size() == 4);
	assert_no_condition(inst);
	assert_no_flags(inst);

	be_parameter modep(*this, inst.param(0), PTYPE_MRI);
	be_parameter pcp(*this, inst.param(1), PTYPE_MRI);
	const parameter &exp = inst.param(2);
	assert(exp.is_code_handle());

	if (!modep.is_immediate())
		mov_reg_param(a, 4, TEMP_REG1, modep);
	if (!pcp.is_immediate())
		mov_reg_param(a, 4, TEMP_REG2, pcp);

	auto index_pc = [&]()
	{
		if (pcp.is_immediate())
		{
			uint32_t const l1val = (pcp.immediate() >> m_hash.l1shift()) & m_hash.l1mask();
			uint32_t const l2val = (pcp.immediate() >> m_hash.l2shift()) & m_hash.l2mask();

			if (l1val)
			{
				if ((l1val * 8) < 2048)
					la_addi_d(&a, SCRATCH_REG2, SCRATCH_REG2, int32_t(l1val * 8));
				else
				{
					load_imm64(a, MEM_SCRATCH_REG, uint64_t(l1val) * 8);
					la_add_d(&a, SCRATCH_REG2, SCRATCH_REG2, MEM_SCRATCH_REG);
				}
			}
			la_ld_d(&a, SCRATCH_REG2, SCRATCH_REG2, 0);

			if (l2val)
			{
				if ((l2val * 8) < 2048)
					la_addi_d(&a, SCRATCH_REG2, SCRATCH_REG2, int32_t(l2val * 8));
				else
				{
					load_imm64(a, MEM_SCRATCH_REG, uint64_t(l2val) * 8);
					la_add_d(&a, SCRATCH_REG2, SCRATCH_REG2, MEM_SCRATCH_REG);
				}
			}
			la_ld_d(&a, SCRATCH_REG2, SCRATCH_REG2, 0);
		}
		else
		{
			if (m_hash.l1bits())
			{
				la_bstrpick_d(&a, MEM_SCRATCH_REG, TEMP_REG2, m_hash.l1shift() + m_hash.l1bits() - 1, m_hash.l1shift());
				la_slli_d(&a, MEM_SCRATCH_REG, MEM_SCRATCH_REG, 3);
				la_add_d(&a, SCRATCH_REG2, SCRATCH_REG2, MEM_SCRATCH_REG);
			}
			la_ld_d(&a, SCRATCH_REG2, SCRATCH_REG2, 0);

			if (m_hash.l2bits())
			{
				la_bstrpick_d(&a, MEM_SCRATCH_REG, TEMP_REG2, m_hash.l2shift() + m_hash.l2bits() - 1, m_hash.l2shift());
				la_slli_d(&a, MEM_SCRATCH_REG, MEM_SCRATCH_REG, 3);
				la_add_d(&a, SCRATCH_REG2, SCRATCH_REG2, MEM_SCRATCH_REG);
			}
			la_ld_d(&a, SCRATCH_REG2, SCRATCH_REG2, 0);
		}
	};

	if (modep.is_immediate() && m_hash.populate_mode(modep.immediate()))
	{
		if (pcp.is_immediate() && !m_invariant_block)
		{
			uint32_t const l1val = (pcp.immediate() >> m_hash.l1shift()) & m_hash.l1mask();
			uint32_t const l2val = (pcp.immediate() >> m_hash.l2shift()) & m_hash.l2mask();
			load_address(a, SCRATCH_REG2, uintptr_t(&m_hash.base()[modep.immediate()][l1val][l2val]));
			la_ld_d(&a, SCRATCH_REG2, SCRATCH_REG2, 0);
		}
		else
		{
			load_imm64(a, SCRATCH_REG2, uintptr_t(m_hash.base()[modep.immediate()]));
			index_pc();
		}
	}
	else
	{
		load_address(a, SCRATCH_REG2, uintptr_t(m_hash.base()));

		if (modep.is_immediate())
		{
			uint64_t const offs = uint64_t(modep.immediate()) * 8;
			if (offs < 2048)
				la_addi_d(&a, SCRATCH_REG2, SCRATCH_REG2, int32_t(offs));
			else
			{
				load_imm64(a, MEM_SCRATCH_REG, offs);
				la_add_d(&a, SCRATCH_REG2, SCRATCH_REG2, MEM_SCRATCH_REG);
			}
		}
		else
		{
			la_slli_d(&a, MEM_SCRATCH_REG, TEMP_REG1, 3);
			la_add_d(&a, SCRATCH_REG2, SCRATCH_REG2, MEM_SCRATCH_REG);
		}
		la_ld_d(&a, SCRATCH_REG2, SCRATCH_REG2, 0);

		index_pc();
	}

	lagoon_label_t const target = {};
	lagoon_label_t target_label = target;
	la_la_local(&a, REG_PARAM1, la_label(&a, &target_label));
	la_jr(&a, SCRATCH_REG2);
	la_bind(&a, &target_label);

	mov_mem_param(a, 4, &m_state.exp, pcp);

	drccodeptr *const targetptr = exp.handle().codeptr_addr();
	if (*targetptr != nullptr)
	{
		load_address(a, SCRATCH_REG2, uintptr_t(*targetptr));
	}
	else
	{
		load_address(a, SCRATCH_REG2, uintptr_t(targetptr));
		la_ld_d(&a, SCRATCH_REG2, SCRATCH_REG2, 0);
	}
	la_jirl(&a, LA_RA, SCRATCH_REG2, 0);

	la_label_free(&a, &target_label);
}

void drcbe_la64::op_jmp(lagoon_assembler_t &a, const uml::instruction &inst)
{
	assert(inst.size() == 4);
	assert_any_condition(inst);
	assert_no_flags(inst);

	const parameter &labelp = inst.param(0);
	assert(labelp.is_code_label());

	lagoon_label_t &target = m_labels[labelp.label()];

	if (inst.condition() == uml::COND_ALWAYS)
	{
		la_b(&a, la_label(&a, &target));
		return;
	}

	// branch island: keep the short-range conditional branch local and use
	// the 26-bit unconditional branch to reach the real target
	lagoon_label_t skip = {};
	emit_skip(a, inst.condition(), skip);
	la_b(&a, la_label(&a, &target));
	la_bind(&a, &skip);
	la_label_free(&a, &skip);
}

std::vector<uint8_t> drcbe_la64::analyze_flag_liveness(const uml::instruction *instlist, uint32_t numinst) const
{
	std::vector<uint8_t> live_in(numinst, 0);
	std::vector<uint32_t> jump_target(numinst, numinst);
	std::map<uint32_t, uint32_t> labels;

	for (uint32_t index = 0; index < numinst; index++)
	{
		uml::instruction const &inst = instlist[index];
		if (inst.opcode() == uml::OP_LABEL)
			labels.emplace(uint32_t(inst.param(0).label()), index);
	}

	for (uint32_t index = 0; index < numinst; index++)
	{
		uml::instruction const &inst = instlist[index];
		if (inst.opcode() == uml::OP_JMP)
		{
			auto const target = labels.find(uint32_t(inst.param(0).label()));
			if (target != labels.end())
				jump_target[index] = target->second;
		}
	}

	bool changed = true;
	while (changed)
	{
		changed = false;
		for (uint32_t index = numinst; index-- > 0; )
		{
			uml::instruction const &inst = instlist[index];
			uint8_t use = inst.input_flags();
			uint8_t kill = inst.modified_flags();
			uint32_t target = numinst;
			bool fallthrough = true;

			switch (inst.opcode())
			{
			case uml::OP_EXIT:
				kill = 0;
				fallthrough = (inst.condition() != uml::COND_ALWAYS);
				break;

			case uml::OP_HASHJMP:
				use = 0;
				kill = 0;
				fallthrough = false;
				break;

			case uml::OP_JMP:
				kill = 0;
				target = jump_target[index];
				if (target >= numinst)
					use |= uml::FLAGS_ALL;
				fallthrough = (inst.condition() != uml::COND_ALWAYS);
				break;

			case uml::OP_EXH:
				use |= uml::FLAGS_ALL;
				kill = 0;
				fallthrough = (inst.condition() != uml::COND_ALWAYS);
				break;

			case uml::OP_CALLH:
				use |= uml::FLAGS_ALL;
				kill = uml::FLAGS_ALL;
				fallthrough = true;
				break;

			case uml::OP_RET:
				kill = (inst.condition() == uml::COND_ALWAYS) ? uint8_t(uml::FLAGS_ALL) : uint8_t(0);
				fallthrough = (inst.condition() != uml::COND_ALWAYS);
				break;

			case uml::OP_CALLC:
				kill = 0;
				fallthrough = true;
				break;

			default:
				if (inst.condition() != uml::COND_ALWAYS)
					kill = 0;
				break;
			}

			uint8_t live = use;
			uint8_t const survive = uint8_t(~kill);
			if (target < numinst)
				live |= live_in[target] & survive;
			if (fallthrough && ((index + 1) < numinst))
				live |= live_in[index + 1] & survive;
			if (live != live_in[index])
			{
				live_in[index] = live;
				changed = true;
			}
		}
	}

	return live_in;
}


bool drcbe_la64::emit_cmp_branch(lagoon_assembler_t &a, uml::condition_t cond, const be_parameter &src1p, const be_parameter &src2p, uint32_t size, lagoon_label_t &target)
{
	if (!condition_is_compare(cond))
		return false;

	mov_reg_param(a, size, TEMP_REG1, src1p);
	mov_reg_param(a, size, TEMP_REG2, src2p);

	switch (cond)
	{
	case uml::COND_Z:  la_beq(&a, TEMP_REG1, TEMP_REG2, la_label(&a, &target)); break;
	case uml::COND_NZ: la_bne(&a, TEMP_REG1, TEMP_REG2, la_label(&a, &target)); break;

	// carry is an unsigned borrow: src1 < src2
	case uml::COND_C:  la_bltu(&a, TEMP_REG1, TEMP_REG2, la_label(&a, &target)); break;
	case uml::COND_NC: la_bgeu(&a, TEMP_REG1, TEMP_REG2, la_label(&a, &target)); break;

	// above/below-or-equal are unsigned compares
	case uml::COND_A:  la_bltu(&a, TEMP_REG2, TEMP_REG1, la_label(&a, &target)); break;
	case uml::COND_BE: la_bgeu(&a, TEMP_REG2, TEMP_REG1, la_label(&a, &target)); break;

	case uml::COND_L:
	case uml::COND_GE:
	case uml::COND_G:
	case uml::COND_LE:
		if (size == 4)
		{
			sign_extend32(a, TEMP_REG1);
			sign_extend32(a, TEMP_REG2);
		}
		if (cond == uml::COND_L)
			la_blt(&a, TEMP_REG1, TEMP_REG2, la_label(&a, &target));
		else if (cond == uml::COND_GE)
			la_bge(&a, TEMP_REG1, TEMP_REG2, la_label(&a, &target));
		else if (cond == uml::COND_G)
			la_blt(&a, TEMP_REG2, TEMP_REG1, la_label(&a, &target));
		else
			la_bge(&a, TEMP_REG2, TEMP_REG1, la_label(&a, &target));
		break;

	case uml::COND_S:
	case uml::COND_NS:
		la_sub_d(&a, TEMP_REG3, TEMP_REG1, TEMP_REG2);
		la_bstrpick_d(&a, TEMP_REG3, TEMP_REG3, (size * 8) - 1, (size * 8) - 1);
		if (cond == uml::COND_S)
			la_bnez(&a, TEMP_REG3, la_label(&a, &target));
		else
			la_beqz(&a, TEMP_REG3, la_label(&a, &target));
		break;

	default:
		return false;
	}
	return true;
}


bool drcbe_la64::emit_test_branch(lagoon_assembler_t &a, uml::condition_t cond, const be_parameter &src1p, const be_parameter &src2p, uint32_t size, lagoon_label_t &target)
{
	switch (cond)
	{
	case uml::COND_Z:
	case uml::COND_NZ:
	case uml::COND_S:
	case uml::COND_NS:
		break;
	default:
		return false;
	}

	mov_reg_param(a, size, TEMP_REG1, src1p);
	mov_reg_param(a, size, TEMP_REG2, src2p);
	la_and(&a, TEMP_REG3, TEMP_REG1, TEMP_REG2);

	switch (cond)
	{
	case uml::COND_Z:  la_beqz(&a, TEMP_REG3, la_label(&a, &target)); break;
	case uml::COND_NZ: la_bnez(&a, TEMP_REG3, la_label(&a, &target)); break;
	case uml::COND_S:
		la_bstrpick_d(&a, TEMP_REG3, TEMP_REG3, (size * 8) - 1, (size * 8) - 1);
		la_bnez(&a, TEMP_REG3, la_label(&a, &target));
		break;
	case uml::COND_NS:
		la_bstrpick_d(&a, TEMP_REG3, TEMP_REG3, (size * 8) - 1, (size * 8) - 1);
		la_beqz(&a, TEMP_REG3, la_label(&a, &target));
		break;
	default:
		return false;
	}
	return true;
}


bool drcbe_la64::try_fuse_cmp_branch(lagoon_assembler_t &a, const uml::instruction *instlist, uint32_t numinst, uint32_t inum, std::vector<uint8_t> const &flag_live_in, uint32_t &consumed)
{
	uml::instruction const &inst = instlist[inum];
	bool const is_cmp = (inst.opcode() == uml::OP_CMP);
	if ((!is_cmp && (inst.opcode() != uml::OP_TEST)) || (inst.condition() != uml::COND_ALWAYS))
		return false;

	uint8_t const cmpflags = inst.flags();
	if (!cmpflags || ((inum + 1) >= numinst))
		return false;

	uml::instruction const &jmp = instlist[inum + 1];
	if ((jmp.opcode() != uml::OP_JMP) || (jmp.condition() == uml::COND_ALWAYS) || (jmp.numparams() != 1) || !jmp.param(0).is_code_label())
		return false;

	uint8_t const produced = is_cmp ? (uml::FLAG_C | uml::FLAG_V | uml::FLAG_Z | uml::FLAG_S) : (uml::FLAG_Z | uml::FLAG_S);
	uint8_t const used = jmp.input_flags();
	if ((used & ~produced) != 0)
		return false;
	if ((used & ~cmpflags) != 0)
		return false;

	// the flag computation can only be dropped if the branch is the last reader
	uint32_t const targetindex = find_label_index(instlist, numinst, jmp.param(0).label());
	if (targetindex >= numinst)
		return false;

	if (((inum + 2) < numinst) && (flag_live_in[inum + 2] & produced))
		return false;
	if (flag_live_in[targetindex] & produced)
		return false;

	be_parameter src1p(*this, inst.param(0), PTYPE_MRI);
	be_parameter src2p(*this, inst.param(1), PTYPE_MRI);
	lagoon_label_t &target = m_labels[jmp.param(0).label()];

	// constant folding: both operands known, or CMP against itself
	uint8_t folded = 0;
	bool have_folded = false;
	if (is_cmp)
	{
		if (src1p.is_immediate() && src2p.is_immediate())
		{
			folded = compute_sub_flags(src1p.immediate(), src2p.immediate(), inst.size());
			have_folded = true;
		}
		else if (src1p == src2p)
		{
			folded = uml::FLAG_Z;
			have_folded = true;
		}
	}
	else
	{
		if (src1p.is_immediate() && src2p.is_immediate())
		{
			folded = compute_nz_flags(src1p.immediate() & src2p.immediate(), inst.size());
			have_folded = true;
		}
		else if (src1p.is_immediate_value(0) || src2p.is_immediate_value(0))
		{
			folded = uml::FLAG_Z;
			have_folded = true;
		}
	}

	if (have_folded)
	{
		if (evaluate_condition(jmp.condition(), folded))
			la_b(&a, la_label(&a, &target));
		consumed = 2;
		return true;
	}

	// use an island: the short conditional branch jumps over the long
	// unconditional branch, keeping the target reach unrestricted
	uml::condition_t const inverse = invert_condition(jmp.condition());
	if (inverse == uml::COND_ALWAYS)
		return false;
	if (!condition_is_compare(inverse))
		return false;
	if (!is_cmp && (inverse != uml::COND_Z) && (inverse != uml::COND_NZ) && (inverse != uml::COND_S) && (inverse != uml::COND_NS))
		return false;

	lagoon_label_t over = {};
	bool const emitted = is_cmp
			? emit_cmp_branch(a, inverse, src1p, src2p, inst.size(), over)
			: emit_test_branch(a, inverse, src1p, src2p, inst.size(), over);
	if (!emitted)
	{
		la_label_free(&a, &over);
		return false;
	}
	la_b(&a, la_label(&a, &target));
	la_bind(&a, &over);
	la_label_free(&a, &over);

	consumed = 2;
	return true;
}


void drcbe_la64::op_exh(lagoon_assembler_t &a, const uml::instruction &inst)
{
	assert_any_condition(inst);
	assert_no_flags(inst);

	const parameter &handp = inst.param(0);
	assert(handp.is_code_handle());
	be_parameter exp(*this, inst.param(1), PTYPE_MRI);

	lagoon_label_t no_exception = {};
	emit_skip(a, inst.condition(), no_exception);

	mov_mem_param(a, 4, &m_state.exp, exp);

	drccodeptr *const targetptr = handp.handle().codeptr_addr();
	if (*targetptr != nullptr)
	{
		load_address(a, SCRATCH_REG2, uintptr_t(*targetptr));
	}
	else
	{
		load_address(a, SCRATCH_REG2, uintptr_t(targetptr));
		la_ld_d(&a, SCRATCH_REG2, SCRATCH_REG2, 0);
	}
	la_jirl(&a, LA_RA, SCRATCH_REG2, 0);

	if (inst.condition() != uml::COND_ALWAYS)
	{
		la_bind(&a, &no_exception);
		la_label_free(&a, &no_exception);
	}
}

