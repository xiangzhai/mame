		la_mul_d(&a, TEMP_REG3, TEMP_REG1, TEMP_REG2);
		la_mulh_d(&a, LA_T3, TEMP_REG1, TEMP_REG2);
		mov_param_reg(a, 8, dstp, TEMP_REG3);

