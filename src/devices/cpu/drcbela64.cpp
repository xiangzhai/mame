la_gpr_t drcbe_la64::load_address(lagoon_assembler_t &a, la_gpr_t reg, uintptr_t addr) const
{
	int64_t const diff = int64_t(addr) - int64_t(uintptr_t(a.cursor));
	if ((diff >= -0x80000000LL) && (diff <= 0x7fffffffLL))
		la_la_local(&a, reg, ptrdiff_t(diff));
	else
		la_load_immediate64(&a, reg, int64_t(addr));
	return reg;
}

