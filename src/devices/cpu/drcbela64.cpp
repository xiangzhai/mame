void drcbe_la64::op_fload(lagoon_assembler_t &a, const uml::instruction &inst)
{
	assert(inst.size() == 4 || inst.size() == 8);
	assert_no_condition(inst);
	assert_no_flags(inst);

	be_parameter dstp(*this, inst.param(0), PTYPE_MF);
	be_parameter basep(*this, inst.param(1), PTYPE_M);
	be_parameter indp(*this, inst.param(2), PTYPE_MRI);

	la_fpr_t const dstreg = TEMPF_REG1;
	load_address(a, TEMP_REG1, uintptr_t(basep.memory()));

	if (indp.is_immediate())
	{
		ptrdiff_t const offset = ptrdiff_t(int32_t(uint32_t(indp.immediate()))) * inst.size();
		load_address(a, MEM_SCRATCH_REG, uintptr_t(reinterpret_cast<uint8_t *>(basep.memory()) + offset));
		if (inst.size() == 4)
			la_fld_s(&a, dstreg, MEM_SCRATCH_REG, 0);
		else
			la_fld_d(&a, dstreg, MEM_SCRATCH_REG, 0);
	}
	else
	{
		mov_reg_param(a, 4, TEMP_REG2, indp);
		sign_extend32(a, TEMP_REG2);
		la_slli_d(&a, TEMP_REG2, TEMP_REG2, (inst.size() == 4) ? 2 : 3);
		la_add_d(&a, TEMP_REG1, TEMP_REG1, TEMP_REG2);
		if (inst.size() == 4)
			la_fld_s(&a, dstreg, TEMP_REG1, 0);
		else
			la_fld_d(&a, dstreg, TEMP_REG1, 0);
	}

	mov_float_param_reg(a, inst.size(), dstp, dstreg);
}

