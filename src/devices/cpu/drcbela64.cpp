void drcbe_la64::op_fcmp(lagoon_assembler_t &a, const uml::instruction &inst)
{
	assert(inst.size() == 4 || inst.size() == 8);
	assert_no_condition(inst);
	assert_flags(inst, FLAG_C | FLAG_Z | FLAG_U);

	be_parameter src1p(*this, inst.param(0), PTYPE_MF);
	be_parameter src2p(*this, inst.param(1), PTYPE_MF);

	la_fpr_t const srcreg1 = src1p.select_register(TEMPF_REG1);
	la_fpr_t const srcreg2 = src2p.select_register(TEMPF_REG2);

	if (inst.size() == 4)
	{
		la_fcmp_cun_s(&a, LA_FCC0, srcreg1, srcreg2);
		la_fcmp_clt_s(&a, LA_FCC1, srcreg1, srcreg2);
		la_fcmp_ceq_s(&a, LA_FCC2, srcreg1, srcreg2);
	}
	else
	{
		la_fcmp_cun_d(&a, LA_FCC0, srcreg1, srcreg2);
		la_fcmp_clt_d(&a, LA_FCC1, srcreg1, srcreg2);
		la_fcmp_ceq_d(&a, LA_FCC2, srcreg1, srcreg2);
	}

	uint8_t const flags = inst.flags() & (uml::FLAG_C | uml::FLAG_Z | uml::FLAG_U);
	if (!flags)
		return;

	// unordered inputs make clt/ceq false, so the three results can simply
	// be shifted into place without a select branch
	if (flags & uml::FLAG_C)
		la_movcf2gr(&a, FLAG_TMP_REG, LA_FCC1);
	else
		la_move(&a, FLAG_TMP_REG, LA_ZERO);

	if (flags & uml::FLAG_Z)
	{
		la_movcf2gr(&a, SCRATCH_REG1, LA_FCC2);
		la_slli_d(&a, SCRATCH_REG1, SCRATCH_REG1, uml::FLAG_BIT_Z);
		la_or(&a, FLAG_TMP_REG, FLAG_TMP_REG, SCRATCH_REG1);
	}

	if (flags & uml::FLAG_U)
	{
		la_movcf2gr(&a, SCRATCH_REG1, LA_FCC0);
		la_slli_d(&a, SCRATCH_REG1, SCRATCH_REG1, uml::FLAG_BIT_U);
		la_or(&a, FLAG_TMP_REG, FLAG_TMP_REG, SCRATCH_REG1);
	}

	merge_flags(a, flags);
}

template <int Opcode> void drcbe_la64::op_float_alu(lagoon_assembler_t &a, const uml::instruction &inst)
{
	assert(inst.size() == 4 || inst.size() == 8);
	assert_no_condition(inst);
	assert_no_flags(inst);

	be_parameter dstp(*this, inst.param(0), PTYPE_MF);
	be_parameter src1p(*this, inst.param(1), PTYPE_MF);
	be_parameter src2p(*this, inst.param(2), PTYPE_MF);

	la_fpr_t const dstreg = TEMPF_REG3;
	la_fpr_t const srcreg1 = TEMPF_REG1;
	la_fpr_t const srcreg2 = TEMPF_REG2;

	mov_float_reg_param(a, inst.size(), srcreg1, src1p);
	mov_float_reg_param(a, inst.size(), srcreg2, src2p);

	if (inst.size() == 4)
	{
		if (Opcode == 0) la_fadd_s(&a, dstreg, srcreg1, srcreg2);
		else if (Opcode == 1) la_fsub_s(&a, dstreg, srcreg1, srcreg2);
		else if (Opcode == 2) la_fmul_s(&a, dstreg, srcreg1, srcreg2);
		else la_fdiv_s(&a, dstreg, srcreg1, srcreg2);
	}
	else
	{
		if (Opcode == 0) la_fadd_d(&a, dstreg, srcreg1, srcreg2);
		else if (Opcode == 1) la_fsub_d(&a, dstreg, srcreg1, srcreg2);
		else if (Opcode == 2) la_fmul_d(&a, dstreg, srcreg1, srcreg2);
		else la_fdiv_d(&a, dstreg, srcreg1, srcreg2);
	}

	mov_float_param_reg(a, inst.size(), dstp, dstreg);
}

template <int Opcode> void drcbe_la64::op_float_alu2(lagoon_assembler_t &a, const uml::instruction &inst)
{
	assert(inst.size() == 4 || inst.size() == 8);
	assert_no_condition(inst);
	assert_no_flags(inst);

	be_parameter dstp(*this, inst.param(0), PTYPE_MF);
	be_parameter srcp(*this, inst.param(1), PTYPE_MF);

	la_fpr_t const dstreg = TEMPF_REG2;
	la_fpr_t const srcreg = TEMPF_REG1;
	la_fpr_t const one = TEMPF_REG3;

	mov_float_reg_param(a, inst.size(), srcreg, srcp);

	switch (Opcode)
	{
	case 0:
		if (inst.size() == 4) la_fneg_s(&a, dstreg, srcreg);
		else la_fneg_d(&a, dstreg, srcreg);
		break;
	case 1:
		if (inst.size() == 4) la_fabs_s(&a, dstreg, srcreg);
		else la_fabs_d(&a, dstreg, srcreg);
		break;
	case 2:
		if (inst.size() == 4) la_fsqrt_s(&a, dstreg, srcreg);
		else la_fsqrt_d(&a, dstreg, srcreg);
		break;
	case 3:
		if (inst.size() == 4)
		{
			emit_float_ldr_state(a, one, &m_near.single1, 4);
			la_fdiv_s(&a, dstreg, one, srcreg);
		}
		else
		{
			emit_float_ldr_state(a, one, &m_near.double1, 8);
			la_fdiv_d(&a, dstreg, one, srcreg);
		}
		break;
	default:
		if (inst.size() == 4)
		{
			la_fsqrt_s(&a, dstreg, srcreg);
			emit_float_ldr_state(a, one, &m_near.single1, 4);
			la_fdiv_s(&a, dstreg, one, dstreg);
		}
		else
		{
			la_fsqrt_d(&a, dstreg, srcreg);
			emit_float_ldr_state(a, one, &m_near.double1, 8);
			la_fdiv_d(&a, dstreg, one, dstreg);
		}
		break;
	}

	mov_float_param_reg(a, inst.size(), dstp, dstreg);
}

void drcbe_la64::op_fcopyi(lagoon_assembler_t &a, const uml::instruction &inst)
{
	assert(inst.size() == 4 || inst.size() == 8);
	assert_no_condition(inst);
	assert_no_flags(inst);

	be_parameter dstp(*this, inst.param(0), PTYPE_MF);
	be_parameter srcp(*this, inst.param(1), PTYPE_MR);

	la_fpr_t const dstreg = TEMPF_REG1;

	mov_reg_param(a, inst.size(), TEMP_REG1, srcp);
	if (inst.size() == 4)
		la_movgr2fr_w(&a, dstreg, TEMP_REG1);
	else
		la_movgr2fr_d(&a, dstreg, TEMP_REG1);

	mov_float_param_reg(a, inst.size(), dstp, dstreg);
}

void drcbe_la64::op_icopyf(lagoon_assembler_t &a, const uml::instruction &inst)
{
	assert(inst.size() == 4 || inst.size() == 8);
	assert_no_condition(inst);
	assert_no_flags(inst);

	be_parameter dstp(*this, inst.param(0), PTYPE_MR);
	be_parameter srcp(*this, inst.param(1), PTYPE_MF);

	la_gpr_t const dstreg = TEMP_REG1;
	la_fpr_t const srcreg = TEMPF_REG1;

	mov_float_reg_param(a, inst.size(), srcreg, srcp);
	if (inst.size() == 4)
	{
		la_movfr2gr_s(&a, dstreg, srcreg);
		zero_extend32(a, dstreg);
	}
	else
	{
		la_movfr2gr_d(&a, dstreg, srcreg);
	}

	mov_param_reg(a, inst.size(), dstp, dstreg);
}

