template <bool Signed> void drcbe_la64::op_div(lagoon_assembler_t &a, const uml::instruction &inst)
{
	assert(inst.size() == 4 || inst.size() == 8);
	assert_no_condition(inst);
	assert_flags(inst, FLAG_V | FLAG_Z | FLAG_S);

	be_parameter dstp(*this, inst.param(0), PTYPE_MR);
	be_parameter edstp(*this, inst.param(1), PTYPE_MR);
	be_parameter src1p(*this, inst.param(2), PTYPE_MRI);
	be_parameter src2p(*this, inst.param(3), PTYPE_MRI);
	const bool compute_rem = (dstp != edstp);

	mov_reg_param(a, inst.size(), TEMP_REG2, src2p);

	lagoon_label_t zero = {};
	lagoon_label_t done = {};
	la_beqz(&a, TEMP_REG2, la_label(&a, &zero));

	mov_reg_param(a, inst.size(), TEMP_REG1, src1p);
	la_gpr_t const quot = dstp.select_register(TEMP_REG3);
	la_gpr_t const rem = edstp.select_register(LA_T3);

	if (inst.size() == 4)
	{
		if (Signed)
		{
			la_div_w(&a, quot, TEMP_REG1, TEMP_REG2);
			if (compute_rem)
				la_mod_w(&a, rem, TEMP_REG1, TEMP_REG2);
		}
		else
		{
			la_div_wu(&a, quot, TEMP_REG1, TEMP_REG2);
			if (compute_rem)
				la_mod_wu(&a, rem, TEMP_REG1, TEMP_REG2);
		}
		zero_extend32(a, quot);
		if (compute_rem)
			zero_extend32(a, rem);
	}
	else
	{
		if (Signed)
		{
			la_div_d(&a, quot, TEMP_REG1, TEMP_REG2);
			if (compute_rem)
				la_mod_d(&a, rem, TEMP_REG1, TEMP_REG2);
		}
		else
		{
			la_div_du(&a, quot, TEMP_REG1, TEMP_REG2);
			if (compute_rem)
				la_mod_du(&a, rem, TEMP_REG1, TEMP_REG2);
		}
	}

	write_result(a, inst.size(), dstp, quot, inst.size() == 4);
	if (compute_rem)
		write_result(a, inst.size(), edstp, rem, inst.size() == 4);

	if (inst.flags())
	{
		emit_flags_nz(a, quot, inst.size() * 8, inst.flags(), FLAG_TMP_REG);
		merge_flags(a, inst.flags());
	}
	la_b(&a, la_label(&a, &done));

	la_bind(&a, &zero);
	if (inst.flags())
		la_addi_d(&a, FLAGS_REG, LA_ZERO, uml::FLAG_V);

	la_bind(&a, &done);
	la_label_free(&a, &zero);
	la_label_free(&a, &done);
}


void drcbe_la64::op_carry(lagoon_assembler_t &a, const uml::instruction &inst)
{
	assert(inst.size() == 4 || inst.size() == 8);
	assert_no_condition(inst);
	assert_flags(inst, FLAG_C);

	be_parameter srcp(*this, inst.param(0), PTYPE_MRI);
	be_parameter bitp(*this, inst.param(1), PTYPE_MRI);
	const int bits = inst.size() * 8;

	if (srcp.is_immediate() && bitp.is_immediate())
	{
		uint64_t const bit = (srcp.immediate() >> (bitp.immediate() & (bits - 1))) & 1;
		if (bit)
			la_ori(&a, FLAGS_REG, FLAGS_REG, uml::FLAG_C);
		else
			la_andi(&a, FLAGS_REG, FLAGS_REG, int32_t(~uml::FLAG_C));
		return;
	}

	mov_reg_param(a, inst.size(), TEMP_REG1, srcp);
	if (bitp.is_immediate())
	{
		la_srli_d(&a, TEMP_REG2, TEMP_REG1, bitp.immediate() % bits);
	}
	else
	{
		mov_reg_param(a, 4, TEMP_REG2, bitp);
		la_andi(&a, TEMP_REG2, TEMP_REG2, bits - 1);
		la_srl_d(&a, TEMP_REG2, TEMP_REG1, TEMP_REG2);
	}
	la_andi(&a, TEMP_REG2, TEMP_REG2, 1);
	la_andi(&a, FLAGS_REG, FLAGS_REG, uml::FLAGS_ALL & ~uml::FLAG_C);
	la_or(&a, FLAGS_REG, FLAGS_REG, TEMP_REG2);
}

void drcbe_la64::op_read(lagoon_assembler_t &a, const uml::instruction &inst)
{
	assert(inst.size() == 4 || inst.size() == 8);
	assert_no_condition(inst);
	assert_no_flags(inst);

	be_parameter dstp(*this, inst.param(0), PTYPE_MR);
	be_parameter addrp(*this, inst.param(1), PTYPE_MRI);
	const parameter &spacesizep = inst.param(2);
	assert(spacesizep.is_size_space());

	auto const &accessors = m_memory_accessors[spacesizep.space()];
	bool const have_specific = (uintptr_t(nullptr) != accessors.specific.read.function) || accessors.specific.read.is_virtual;

	emit_fcsr_sync_if_changed(a);

	if (have_specific && ((1 << spacesizep.size()) == accessors.specific.native_bytes))
	{
		emit_memaccess_setup(a, addrp, accessors, accessors.specific.read);
		if (accessors.specific.native_bytes >= 8)
			load_imm64(a, REG_PARAM3, ~uint64_t(0));
		else
			load_imm32(a, REG_PARAM3, uint32_t((uint64_t(1) << (accessors.specific.native_bytes * 8)) - 1));
		emit_specific_call(a, accessors.specific.read);
	}
	else if (have_specific && ((1 << spacesizep.size()) < accessors.specific.native_bytes))
	{
		if (spacesizep.size() == SIZE_BYTE)
			load_imm32(a, REG_PARAM3, 0xff);
		else if (spacesizep.size() == SIZE_WORD)
			load_imm32(a, REG_PARAM3, 0xffff);
		else
			load_imm32(a, REG_PARAM3, 0xffffffff);
		emit_narrow_memread(a, addrp, spacesizep, accessors);
	}
	else
	{
		mov_reg_param(a, 4, REG_PARAM2, addrp);
		uintptr_t func = 0;
		if (spacesizep.size() == SIZE_BYTE)
			func = uintptr_t(accessors.resolved.read_byte.func);
		else if (spacesizep.size() == SIZE_WORD)
			func = uintptr_t(accessors.resolved.read_word.func);
		else if (spacesizep.size() == SIZE_DWORD)
			func = uintptr_t(accessors.resolved.read_dword.func);
		else
			func = uintptr_t(accessors.resolved.read_qword.func);
		uintptr_t const obj = (spacesizep.size() == SIZE_BYTE) ? accessors.resolved.read_byte.obj :
				(spacesizep.size() == SIZE_WORD) ? accessors.resolved.read_word.obj :
				(spacesizep.size() == SIZE_DWORD) ? accessors.resolved.read_dword.obj :
				accessors.resolved.read_qword.obj;
		load_address(a, REG_PARAM1, obj);
		call_helper_addr(a, func);
	}

	if (spacesizep.size() == SIZE_BYTE)
		la_andi(&a, REG_PARAM1, REG_PARAM1, 0xff);
	else if (spacesizep.size() == SIZE_WORD)
		la_bstrpick_d(&a, REG_PARAM1, REG_PARAM1, 15, 0);
	else if (spacesizep.size() == SIZE_DWORD)
		zero_extend32(a, REG_PARAM1);
	else if (inst.size() == 4)
		zero_extend32(a, REG_PARAM1);

	mov_param_reg(a, inst.size(), dstp, REG_PARAM1);
	emit_fcsr_sync_if_changed(a);
}

void drcbe_la64::op_readm(lagoon_assembler_t &a, const uml::instruction &inst)
{
	assert(inst.size() == 4 || inst.size() == 8);
	assert_no_condition(inst);
	assert_no_flags(inst);

	be_parameter dstp(*this, inst.param(0), PTYPE_MR);
	be_parameter addrp(*this, inst.param(1), PTYPE_MRI);
	be_parameter maskp(*this, inst.param(2), PTYPE_MRI);
	const parameter &spacesizep = inst.param(3);
	assert(spacesizep.is_size_space());

	auto const &accessors = m_memory_accessors[spacesizep.space()];
	bool const have_specific = (uintptr_t(nullptr) != accessors.specific.read.function) || accessors.specific.read.is_virtual;

	emit_fcsr_sync_if_changed(a);

	if (have_specific && ((1 << spacesizep.size()) == accessors.specific.native_bytes))
	{
		emit_memaccess_setup(a, addrp, accessors, accessors.specific.read);
		mov_reg_param(a, inst.size(), REG_PARAM3, maskp);
		emit_specific_call(a, accessors.specific.read);
	}
	else if (have_specific && ((1 << spacesizep.size()) < accessors.specific.native_bytes))
	{
		mov_reg_param(a, inst.size(), REG_PARAM3, maskp);
		emit_narrow_memread(a, addrp, spacesizep, accessors);
	}
	else
	{
		mov_reg_param(a, 4, REG_PARAM2, addrp);
		mov_reg_param(a, inst.size(), REG_PARAM3, maskp);
		uintptr_t func = 0;
		uintptr_t obj = 0;
		if (spacesizep.size() == SIZE_BYTE)
		{
			func = uintptr_t(accessors.resolved.read_byte_masked.func);
			obj = accessors.resolved.read_byte_masked.obj;
		}
		else if (spacesizep.size() == SIZE_WORD)
		{
			func = uintptr_t(accessors.resolved.read_word_masked.func);
			obj = accessors.resolved.read_word_masked.obj;
		}
		else if (spacesizep.size() == SIZE_DWORD)
		{
			func = uintptr_t(accessors.resolved.read_dword_masked.func);
			obj = accessors.resolved.read_dword_masked.obj;
		}
		else
		{
			func = uintptr_t(accessors.resolved.read_qword_masked.func);
			obj = accessors.resolved.read_qword_masked.obj;
		}
		load_address(a, REG_PARAM1, obj);
		call_helper_addr(a, func);
	}

	if (spacesizep.size() == SIZE_BYTE)
		la_andi(&a, REG_PARAM1, REG_PARAM1, 0xff);
	else if (spacesizep.size() == SIZE_WORD)
		la_bstrpick_d(&a, REG_PARAM1, REG_PARAM1, 15, 0);
	else if (spacesizep.size() == SIZE_DWORD)
		zero_extend32(a, REG_PARAM1);
	else if (inst.size() == 4)
		zero_extend32(a, REG_PARAM1);

	mov_param_reg(a, inst.size(), dstp, REG_PARAM1);
	emit_fcsr_sync_if_changed(a);
}

void drcbe_la64::op_write(lagoon_assembler_t &a, const uml::instruction &inst)
{
	assert(inst.size() == 4 || inst.size() == 8);
	assert_no_condition(inst);
	assert_no_flags(inst);

	be_parameter addrp(*this, inst.param(0), PTYPE_MRI);
	be_parameter srcp(*this, inst.param(1), PTYPE_MRI);
	const parameter &spacesizep = inst.param(2);
	assert(spacesizep.is_size_space());

	auto const &accessors = m_memory_accessors[spacesizep.space()];
	bool const have_specific = (uintptr_t(nullptr) != accessors.specific.write.function) || accessors.specific.write.is_virtual;

	emit_fcsr_sync_if_changed(a);

	if (have_specific && ((1 << spacesizep.size()) == accessors.specific.native_bytes))
	{
		emit_memaccess_setup(a, addrp, accessors, accessors.specific.write);
		mov_reg_param(a, inst.size(), REG_PARAM3, srcp);
		if (accessors.specific.native_bytes >= 8)
			load_imm64(a, REG_PARAM4, ~uint64_t(0));
		else
			load_imm32(a, REG_PARAM4, uint32_t((uint64_t(1) << (accessors.specific.native_bytes * 8)) - 1));
		emit_specific_call(a, accessors.specific.write);
	}
	else if (have_specific && ((1 << spacesizep.size()) < accessors.specific.native_bytes))
	{
		mov_reg_param(a, inst.size(), REG_PARAM3, srcp);
		if (spacesizep.size() == SIZE_BYTE)
			load_imm32(a, REG_PARAM4, 0xff);
		else if (spacesizep.size() == SIZE_WORD)
			load_imm32(a, REG_PARAM4, 0xffff);
		else
			load_imm32(a, REG_PARAM4, 0xffffffff);
		emit_narrow_memwrite(a, addrp, spacesizep, accessors);
	}
	else
	{
		mov_reg_param(a, 4, REG_PARAM2, addrp);
		mov_reg_param(a, inst.size(), REG_PARAM3, srcp);
		uintptr_t func = 0;
		uintptr_t obj = 0;
		if (spacesizep.size() == SIZE_BYTE)
		{
			func = uintptr_t(accessors.resolved.write_byte.func);
			obj = accessors.resolved.write_byte.obj;
		}
		else if (spacesizep.size() == SIZE_WORD)
		{
			func = uintptr_t(accessors.resolved.write_word.func);
			obj = accessors.resolved.write_word.obj;
		}
		else if (spacesizep.size() == SIZE_DWORD)
		{
			func = uintptr_t(accessors.resolved.write_dword.func);
			obj = accessors.resolved.write_dword.obj;
		}
		else
		{
			func = uintptr_t(accessors.resolved.write_qword.func);
			obj = accessors.resolved.write_qword.obj;
		}
		load_address(a, REG_PARAM1, obj);
		call_helper_addr(a, func);
	}

	emit_fcsr_sync_if_changed(a);
}

