void drcbe_la64::op_sext(lagoon_assembler_t &a, const uml::instruction &inst)
{
	assert(inst.size() == 4 || inst.size() == 8);
	assert_no_condition(inst);
	assert_flags(inst, FLAG_S | FLAG_Z);

	be_parameter dstp(*this, inst.param(0), PTYPE_MR);
	be_parameter srcp(*this, inst.param(1), PTYPE_MRI);
	const parameter &sizep = inst.param(2);
	assert(sizep.is_size());
	const auto size = sizep.size();

	la_gpr_t const dst = TEMP_REG3;

	if ((1 << size) >= inst.size())
	{
		mov_param_param(a, inst.size(), dstp, srcp);
		if (inst.flags())
		{
			mov_reg_param(a, inst.size(), dst, dstp);
			emit_flags_nz(a, dst, inst.size() * 8, FLAG_TMP_REG);
			merge_flags(a, FLAG_Z | FLAG_S);
		}
		return;
	}

	if (srcp.is_memory())
	{
		uintptr_t mem = uintptr_t(srcp.memory());
		if (size == SIZE_BYTE)
			emit_ldrsb_mem(a, dst, reinterpret_cast<void *>(mem));
		else if (size == SIZE_WORD)
			emit_ldrsh_mem(a, dst, reinterpret_cast<void *>(mem));
		else if (size == SIZE_DWORD)
			emit_ldrsw_mem(a, dst, reinterpret_cast<void *>(mem));
		else
			emit_ldr_mem(a, dst, reinterpret_cast<void *>(mem));
	}
	else
	{
		la_gpr_t const temp = (srcp.is_int_register() ? srcp.get_register_int(inst.size()) : TEMP_REG1);
		mov_reg_param(a, (size == SIZE_QWORD) ? 8 : 4, temp, srcp);

		if (size == SIZE_BYTE)
		{
			la_slli_d(&a, dst, temp, 56);
			la_srai_d(&a, dst, dst, 56);
		}
		else if (size == SIZE_WORD)
		{
			la_slli_d(&a, dst, temp, 48);
			la_srai_d(&a, dst, dst, 48);
		}
		else if (size == SIZE_DWORD)
		{
			if (inst.size() == 8)
			{
				la_slli_d(&a, dst, temp, 32);
				la_srai_d(&a, dst, dst, 32);
			}
			else
			{
				la_move(&a, dst, temp);
			}
		}
		else
		{
			la_move(&a, dst, temp);
		}
	}

	if (inst.size() == 4)
		zero_extend32(a, dst);

	mov_param_reg(a, inst.size(), dstp, dst);

	if (inst.flags())
	{
		emit_flags_nz(a, dst, inst.size() * 8, FLAG_TMP_REG);
		merge_flags(a, FLAG_Z | FLAG_S);
	}
}

