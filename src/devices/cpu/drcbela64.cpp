void drcbe_la64::emit_condition(lagoon_assembler_t &a, uml::condition_t cond, la_gpr_t dst)
{
	switch (cond)
	{
	case uml::COND_ALWAYS:
		la_addi_d(&a, dst, LA_ZERO, 1);
		break;

	case uml::COND_Z:
		la_srli_d(&a, dst, FLAGS_REG, uml::FLAG_BIT_Z);
		la_andi(&a, dst, dst, 1);
		break;
	case uml::COND_NZ:
		la_srli_d(&a, dst, FLAGS_REG, uml::FLAG_BIT_Z);
		la_andi(&a, dst, dst, 1);
		la_xori(&a, dst, dst, 1);
		break;

	case uml::COND_S:
		la_srli_d(&a, dst, FLAGS_REG, uml::FLAG_BIT_S);
		la_andi(&a, dst, dst, 1);
		break;
	case uml::COND_NS:
		la_srli_d(&a, dst, FLAGS_REG, uml::FLAG_BIT_S);
		la_andi(&a, dst, dst, 1);
		la_xori(&a, dst, dst, 1);
		break;

	case uml::COND_C:
		la_andi(&a, dst, FLAGS_REG, uml::FLAG_C);
		break;
	case uml::COND_NC:
		la_andi(&a, dst, FLAGS_REG, uml::FLAG_C);
		la_xori(&a, dst, dst, 1);
		break;

	case uml::COND_V:
		la_srli_d(&a, dst, FLAGS_REG, uml::FLAG_BIT_V);
		la_andi(&a, dst, dst, 1);
		break;
	case uml::COND_NV:
		la_srli_d(&a, dst, FLAGS_REG, uml::FLAG_BIT_V);
		la_andi(&a, dst, dst, 1);
		la_xori(&a, dst, dst, 1);
		break;

	case uml::COND_U:
		la_srli_d(&a, dst, FLAGS_REG, uml::FLAG_BIT_U);
		la_andi(&a, dst, dst, 1);
		break;
	case uml::COND_NU:
		la_srli_d(&a, dst, FLAGS_REG, uml::FLAG_BIT_U);
		la_andi(&a, dst, dst, 1);
		la_xori(&a, dst, dst, 1);
		break;

	case uml::COND_A:
		la_andi(&a, dst, FLAGS_REG, uml::FLAG_C);
		la_xori(&a, dst, dst, 1);
		la_srli_d(&a, LA_T3, FLAGS_REG, uml::FLAG_BIT_Z);
		la_andi(&a, LA_T3, LA_T3, 1);
		la_xori(&a, LA_T3, LA_T3, 1);
		la_and(&a, dst, dst, LA_T3);
		break;
	case uml::COND_BE:
		la_andi(&a, dst, FLAGS_REG, uml::FLAG_C);
		la_srli_d(&a, LA_T3, FLAGS_REG, uml::FLAG_BIT_Z);
		la_andi(&a, LA_T3, LA_T3, 1);
		la_or(&a, dst, dst, LA_T3);
		break;

	case uml::COND_G:
	case uml::COND_LE:
	case uml::COND_L:
	case uml::COND_GE:
		{
			la_srli_d(&a, LA_T3, FLAGS_REG, uml::FLAG_BIT_S);
			la_srli_d(&a, LA_T4, FLAGS_REG, uml::FLAG_BIT_V);
			la_xor(&a, LA_T3, LA_T3, LA_T4);
			la_andi(&a, LA_T3, LA_T3, 1);

			if (cond == uml::COND_L)
			{
				la_move(&a, dst, LA_T3);
			}
			else if (cond == uml::COND_GE)
			{
				la_xori(&a, dst, LA_T3, 1);
			}
			else if (cond == uml::COND_G)
			{
				la_xori(&a, LA_T3, LA_T3, 1);
				la_srli_d(&a, dst, FLAGS_REG, uml::FLAG_BIT_Z);
				la_andi(&a, dst, dst, 1);
				la_xori(&a, dst, dst, 1);
				la_and(&a, dst, dst, LA_T3);
			}
			else
			{
				la_srli_d(&a, dst, FLAGS_REG, uml::FLAG_BIT_Z);
				la_andi(&a, dst, dst, 1);
				la_or(&a, dst, dst, LA_T3);
			}
		}
		break;

	default:
		throw emu_fatalerror("drcbe_la64: invalid condition %u\n", unsigned(cond));
	}
}

void drcbe_la64::emit_flag_branch(lagoon_assembler_t &a, uml::condition_t cond, bool branch_on_true, lagoon_label_t &target)
{
	if (cond == uml::COND_ALWAYS)
	{
		if (branch_on_true)
			la_b(&a, la_label(&a, &target));
		return;
	}

	auto branch_if_nonzero = [&a, &target](bool nonzero)
	{
		if (nonzero)
			la_bnez(&a, SCRATCH_REG1, la_label(&a, &target));
		else
			la_beqz(&a, SCRATCH_REG1, la_label(&a, &target));
	};

	switch (cond)
	{
	case uml::COND_Z:  la_andi(&a, SCRATCH_REG1, FLAGS_REG, uml::FLAG_Z); branch_if_nonzero(branch_on_true);  break;
	case uml::COND_NZ: la_andi(&a, SCRATCH_REG1, FLAGS_REG, uml::FLAG_Z); branch_if_nonzero(!branch_on_true); break;

	case uml::COND_S:  la_andi(&a, SCRATCH_REG1, FLAGS_REG, uml::FLAG_S); branch_if_nonzero(branch_on_true);  break;
	case uml::COND_NS: la_andi(&a, SCRATCH_REG1, FLAGS_REG, uml::FLAG_S); branch_if_nonzero(!branch_on_true); break;

	case uml::COND_C:  la_andi(&a, SCRATCH_REG1, FLAGS_REG, uml::FLAG_C); branch_if_nonzero(branch_on_true);  break;
	case uml::COND_NC: la_andi(&a, SCRATCH_REG1, FLAGS_REG, uml::FLAG_C); branch_if_nonzero(!branch_on_true); break;

	case uml::COND_V:  la_andi(&a, SCRATCH_REG1, FLAGS_REG, uml::FLAG_V); branch_if_nonzero(branch_on_true);  break;
	case uml::COND_NV: la_andi(&a, SCRATCH_REG1, FLAGS_REG, uml::FLAG_V); branch_if_nonzero(!branch_on_true); break;

	case uml::COND_U:  la_andi(&a, SCRATCH_REG1, FLAGS_REG, uml::FLAG_U); branch_if_nonzero(branch_on_true);  break;
	case uml::COND_NU: la_andi(&a, SCRATCH_REG1, FLAGS_REG, uml::FLAG_U); branch_if_nonzero(!branch_on_true); break;

	case uml::COND_A:
		la_andi(&a, SCRATCH_REG1, FLAGS_REG, uml::FLAG_C | uml::FLAG_Z);
		branch_if_nonzero(!branch_on_true);
		break;
	case uml::COND_BE:
		la_andi(&a, SCRATCH_REG1, FLAGS_REG, uml::FLAG_C | uml::FLAG_Z);
		branch_if_nonzero(branch_on_true);
		break;

	case uml::COND_L:
	case uml::COND_GE:
		// move V to the S position, then xor: bit 3 becomes S^V
		la_slli_d(&a, SCRATCH_REG1, FLAGS_REG, uml::FLAG_BIT_S - uml::FLAG_BIT_V);
		la_xor(&a, SCRATCH_REG1, SCRATCH_REG1, FLAGS_REG);
		la_andi(&a, SCRATCH_REG1, SCRATCH_REG1, uml::FLAG_S);
		branch_if_nonzero(cond == uml::COND_L ? branch_on_true : !branch_on_true);
		break;

	case uml::COND_G:
	case uml::COND_LE:
		// extract S:Z:V, then reduce it to (S^V) | Z without pollution
		la_bstrpick_d(&a, SCRATCH_REG1, FLAGS_REG, uml::FLAG_BIT_S, uml::FLAG_BIT_V);
		la_srli_d(&a, SCRATCH_REG2, SCRATCH_REG1, uml::FLAG_BIT_S - uml::FLAG_BIT_V);
		la_xor(&a, SCRATCH_REG1, SCRATCH_REG2, SCRATCH_REG1);
		la_andi(&a, SCRATCH_REG1, SCRATCH_REG1, 3);
		branch_if_nonzero(cond == uml::COND_LE ? branch_on_true : !branch_on_true);
		break;

	default:
		throw emu_fatalerror("drcbe_la64: invalid condition %u\n", unsigned(cond));
	}
}

void drcbe_la64::emit_skip(lagoon_assembler_t &a, uml::condition_t cond, lagoon_label_t &skip)
{
	emit_flag_branch(a, cond, false, skip);
}

void drcbe_la64::emit_flags_nz(lagoon_assembler_t &a, la_gpr_t reg, int bits, uint8_t mask, la_gpr_t output)
{
	uint8_t const needed = mask & (uml::FLAG_Z | uml::FLAG_S);
	if (!needed)
	{
		// the caller may add C/V below; make sure the accumulator starts clean
		la_move(&a, output, LA_ZERO);
		return;
	}

	if (needed & uml::FLAG_Z)
	{
		la_sltui(&a, output, reg, 1);
		la_slli_d(&a, output, output, uml::FLAG_BIT_Z);
	}

	if (needed & uml::FLAG_S)
	{
		if (needed & uml::FLAG_Z)
		{
			la_srli_d(&a, SCRATCH_REG1, reg, bits - 1);
			la_andi(&a, SCRATCH_REG1, SCRATCH_REG1, 1);
			la_slli_d(&a, SCRATCH_REG1, SCRATCH_REG1, uml::FLAG_BIT_S);
			la_or(&a, output, output, SCRATCH_REG1);
		}
		else
		{
			la_srli_d(&a, output, reg, bits - 1);
			la_andi(&a, output, output, 1);
			la_slli_d(&a, output, output, uml::FLAG_BIT_S);
		}
	}
}

void drcbe_la64::emit_flags_add(lagoon_assembler_t &a, la_gpr_t result, la_gpr_t src1, la_gpr_t src2, int bits, bool carryin, uint8_t mask)
{
	uint8_t const needed = mask & (uml::FLAG_C | uml::FLAG_V | uml::FLAG_Z | uml::FLAG_S);
	if (!needed)
		return;

	emit_flags_nz(a, result, bits, needed, FLAG_TMP_REG);

	if (needed & uml::FLAG_C)
	{
		if (!carryin)
		{
			la_sltu(&a, SCRATCH_REG1, result, src1);
		}
		else
		{
			la_and(&a, SCRATCH_REG1, src1, src2);
			la_or(&a, SCRATCH_REG2, src1, src2);
			la_nor(&a, LA_T3, result, LA_ZERO);
			la_and(&a, LA_T3, LA_T3, SCRATCH_REG2);
			la_or(&a, SCRATCH_REG1, SCRATCH_REG1, LA_T3);
			la_srli_d(&a, SCRATCH_REG1, SCRATCH_REG1, bits - 1);
			la_andi(&a, SCRATCH_REG1, SCRATCH_REG1, 1);
		}
		la_or(&a, FLAG_TMP_REG, FLAG_TMP_REG, SCRATCH_REG1);
	}

	if (needed & uml::FLAG_V)
	{
		la_xor(&a, SCRATCH_REG1, src1, src2);
		la_nor(&a, SCRATCH_REG1, SCRATCH_REG1, LA_ZERO);
		la_xor(&a, SCRATCH_REG2, src1, result);
		la_and(&a, SCRATCH_REG1, SCRATCH_REG1, SCRATCH_REG2);
		la_srli_d(&a, SCRATCH_REG1, SCRATCH_REG1, bits - 1);
		la_andi(&a, SCRATCH_REG1, SCRATCH_REG1, 1);
		la_slli_d(&a, SCRATCH_REG1, SCRATCH_REG1, uml::FLAG_BIT_V);
		la_or(&a, FLAG_TMP_REG, FLAG_TMP_REG, SCRATCH_REG1);
	}
}

void drcbe_la64::emit_flags_sub(lagoon_assembler_t &a, la_gpr_t result, la_gpr_t src1, la_gpr_t src2, int bits, bool borrowin, uint8_t mask)
{
	uint8_t const needed = mask & (uml::FLAG_C | uml::FLAG_V | uml::FLAG_Z | uml::FLAG_S);
	if (!needed)
		return;

	emit_flags_nz(a, result, bits, needed, FLAG_TMP_REG);

	if (needed & uml::FLAG_C)
	{
		if (!borrowin)
		{
			la_sltu(&a, SCRATCH_REG1, src1, src2);
		}
		else
		{
			la_nor(&a, SCRATCH_REG1, src1, LA_ZERO);
			la_and(&a, SCRATCH_REG1, SCRATCH_REG1, src2);
			la_nor(&a, SCRATCH_REG2, src1, LA_ZERO);
			la_or(&a, SCRATCH_REG2, SCRATCH_REG2, src2);
			la_and(&a, LA_T3, result, SCRATCH_REG2);
			la_or(&a, SCRATCH_REG1, SCRATCH_REG1, LA_T3);
			la_srli_d(&a, SCRATCH_REG1, SCRATCH_REG1, bits - 1);
			la_andi(&a, SCRATCH_REG1, SCRATCH_REG1, 1);
		}
		la_or(&a, FLAG_TMP_REG, FLAG_TMP_REG, SCRATCH_REG1);
	}

	if (needed & uml::FLAG_V)
	{
		la_xor(&a, SCRATCH_REG1, src1, src2);
		la_xor(&a, SCRATCH_REG2, src1, result);
		la_and(&a, SCRATCH_REG1, SCRATCH_REG1, SCRATCH_REG2);
		la_srli_d(&a, SCRATCH_REG1, SCRATCH_REG1, bits - 1);
		la_andi(&a, SCRATCH_REG1, SCRATCH_REG1, 1);
		la_slli_d(&a, SCRATCH_REG1, SCRATCH_REG1, uml::FLAG_BIT_V);
		la_or(&a, FLAG_TMP_REG, FLAG_TMP_REG, SCRATCH_REG1);
	}
}

void drcbe_la64::merge_flags(lagoon_assembler_t &a, uint8_t mask)
{
	if (!mask)
		return;

	if (mask == uml::FLAGS_ALL)
	{
		la_move(&a, FLAGS_REG, FLAG_TMP_REG);
		return;
	}

	la_andi(&a, SCRATCH_REG1, FLAGS_REG, uint8_t(~mask) & uml::FLAGS_ALL);
	la_andi(&a, FLAG_TMP_REG, FLAG_TMP_REG, mask);
	la_or(&a, FLAGS_REG, SCRATCH_REG1, FLAG_TMP_REG);
}


void drcbe_la64::emit_sync_fcsr(lagoon_assembler_t &a) const
{
	emit_ldr_state_b(a, TEMP_REG2, &m_state.fmod);
	la_andi(&a, TEMP_REG2, TEMP_REG2, 3);
	la_xori(&a, TEMP_REG2, TEMP_REG2, 1);
	la_slli_d(&a, TEMP_REG2, TEMP_REG2, 8);
	la_movfcsr2gr(&a, TEMP_REG1, LA_FCSR0);
	la_bstrins_d(&a, TEMP_REG1, TEMP_REG2, 9, 8);
	la_movgr2fcsr(&a, LA_FCSR0, TEMP_REG1);
}

void drcbe_la64::emit_fcsr_sync_if_changed(lagoon_assembler_t &a) const
{
	// branch over just the FCSR write; the caller's operation must still run
	lagoon_label_t skip = {};
	emit_ldr_state_b(a, FLAGS_REG, &m_near.fmod_changed);
	la_beqz(&a, FLAGS_REG, la_label(&a, &skip));
	emit_sync_fcsr(a);
	la_bind(&a, &skip);
	la_label_free(&a, &skip);
}

void drcbe_la64::call_helper_addr(lagoon_assembler_t &a, uintptr_t addr) const
{
	if (addr)
	{
		load_address(a, SCRATCH_REG1, addr);
		la_jirl(&a, LA_RA, SCRATCH_REG1, 0);
	}
}


void drcbe_la64::mov_reg_param(lagoon_assembler_t &a, uint32_t regsize, la_gpr_t dst, const be_parameter &src) const
{
	if (src.is_immediate())
	{
		if (regsize == 4)
			load_imm32(a, dst, uint32_t(src.immediate()));
		else
			load_imm64(a, dst, src.immediate());
	}
	else if (src.is_int_register())
	{
		la_gpr_t const srcreg = src.get_register_int(regsize);
		if (dst != srcreg)
			la_move(&a, dst, srcreg);

		// the source may still hold a 64-bit value, so a 32-bit read has
		// to truncate even when source and destination are the same
		if (regsize == 4)
			zero_extend32(a, dst);
	}
	else if (src.is_memory())
	{
		if (regsize == 4)
		{
			la_gpr_t const addr = (dst == MEM_SCRATCH_REG) ? SCRATCH_REG1 : MEM_SCRATCH_REG;
			load_address(a, addr, uintptr_t(src.memory()));
			la_ld_wu(&a, dst, addr, 0);
		}
		else
		{
			emit_ldr_mem(a, dst, src.memory());
		}
	}
}

void drcbe_la64::mov_param_reg(lagoon_assembler_t &a, uint32_t regsize, const be_parameter &dst, la_gpr_t src) const
{
	assert(!dst.is_immediate());

	if (dst.is_memory())
	{
		if (dst.is_cold_register())
		{
			if (regsize == 4)
			{
				la_move(&a, LA_T4, src);
				zero_extend32(a, LA_T4);
				src = LA_T4;
			}
			emit_str_mem(a, src, dst.memory());
		}
		else
		{
			la_gpr_t const addr = (src == MEM_SCRATCH_REG) ? SCRATCH_REG1 : MEM_SCRATCH_REG;
			load_address(a, addr, uintptr_t(dst.memory()));
			if (regsize == 4)
				la_st_w(&a, src, addr, 0);
			else
				la_st_d(&a, src, addr, 0);
		}
	}
	else if (dst.is_int_register())
	{
		la_gpr_t const dstreg = dst.get_register_int(regsize);
		if (dstreg != src)
			la_move(&a, dstreg, src);
		if (regsize == 4)
			zero_extend32(a, dstreg);
	}
}

void drcbe_la64::write_result(lagoon_assembler_t &a, uint32_t regsize, const be_parameter &dst, la_gpr_t result, bool already_extended) const
{
	if (dst.is_int_register())
	{
		la_gpr_t const dstreg = dst.get_register_int(regsize);
		if ((regsize == 4) && !already_extended)
			zero_extend32(a, result);
		if (dstreg != result)
			la_move(&a, dstreg, result);
	}
	else
	{
		mov_param_reg(a, regsize, dst, result);
	}
}

void drcbe_la64::mov_param_imm(lagoon_assembler_t &a, uint32_t regsize, const be_parameter &dst, uint64_t src) const
{
	assert(!dst.is_immediate());

	if (dst.is_memory())
	{
		la_gpr_t const temp = SCRATCH_REG1;
		if (regsize == 4)
			load_imm32(a, temp, uint32_t(src));
		else
			load_imm64(a, temp, src);
		if (dst.is_cold_register())
			emit_str_mem(a, temp, dst.memory());
		else
		{
			la_gpr_t const addr = MEM_SCRATCH_REG;
			load_address(a, addr, uintptr_t(dst.memory()));
			if (regsize == 4)
				la_st_w(&a, temp, addr, 0);
			else
				la_st_d(&a, temp, addr, 0);
		}
	}
	else if (dst.is_int_register())
	{
		if (regsize == 4)
			load_imm32(a, dst.get_register_int(regsize), uint32_t(src));
		else
			load_imm64(a, dst.get_register_int(regsize), src);
	}
}

void drcbe_la64::mov_param_param(lagoon_assembler_t &a, uint32_t regsize, const be_parameter &dst, const be_parameter &src) const
{
	assert(!src.is_immediate());
	assert(!dst.is_immediate());

	if (dst.is_int_register())
	{
		mov_reg_param(a, regsize, dst.get_register_int(regsize), src);
	}
	else if (src.is_int_register())
	{
		mov_param_reg(a, regsize, dst, src.get_register_int(regsize));
	}
	else
	{
		mov_reg_param(a, regsize, SCRATCH_REG1, src);
		mov_param_reg(a, regsize, dst, SCRATCH_REG1);
	}
}

void drcbe_la64::mov_mem_param(lagoon_assembler_t &a, uint32_t regsize, void *dst, const be_parameter &src) const
{
	if (src.is_immediate_value(0))
	{
		la_gpr_t const addr = MEM_SCRATCH_REG;
		load_address(a, addr, uintptr_t(dst));
		if (regsize == 4)
			la_st_w(&a, LA_ZERO, addr, 0);
		else
			la_st_d(&a, LA_ZERO, addr, 0);
	}
	else
	{
		mov_reg_param(a, regsize, SCRATCH_REG1, src);
		la_gpr_t const addr = MEM_SCRATCH_REG;
		load_address(a, addr, uintptr_t(dst));
		if (regsize == 4)
			la_st_w(&a, SCRATCH_REG1, addr, 0);
		else
			la_st_d(&a, SCRATCH_REG1, addr, 0);
	}
}

void drcbe_la64::mov_float_reg_param(lagoon_assembler_t &a, uint32_t regsize, la_fpr_t dst, const be_parameter &src) const
{
	assert(!src.is_immediate());

	if (src.is_memory())
		emit_float_ldr_mem(a, dst, src.memory(), regsize);
	else if (src.is_float_register() && dst != src.get_register_float(regsize))
	{
		if (regsize == 4)
			la_fmov_s(&a, dst, src.get_register_float(regsize));
		else
			la_fmov_d(&a, dst, src.get_register_float(regsize));
	}
}

void drcbe_la64::mov_float_param_reg(lagoon_assembler_t &a, uint32_t regsize, const be_parameter &dst, la_fpr_t src) const
{
	assert(!dst.is_immediate());

	if (dst.is_memory())
		emit_float_str_mem(a, src, dst.memory(), regsize);
	else if (dst.is_float_register() && src != dst.get_register_float(regsize))
	{
		if (regsize == 4)
			la_fmov_s(&a, dst.get_register_float(regsize), src);
		else
			la_fmov_d(&a, dst.get_register_float(regsize), src);
	}
}

void drcbe_la64::mov_float_param_int_reg(lagoon_assembler_t &a, uint32_t regsize, const be_parameter &dst, la_gpr_t src) const
{
	assert(!dst.is_immediate());

	if (dst.is_memory())
	{
		la_gpr_t const addr = (src == MEM_SCRATCH_REG) ? SCRATCH_REG1 : MEM_SCRATCH_REG;
		load_address(a, addr, uintptr_t(dst.memory()));
		if (regsize == 4)
			la_st_w(&a, src, addr, 0);
		else
			la_st_d(&a, src, addr, 0);
	}
	else if (dst.is_float_register())
	{
		if (regsize == 4)
			la_movgr2fr_w(&a, dst.get_register_float(regsize), src);
		else
			la_movgr2fr_d(&a, dst.get_register_float(regsize), src);
	}
}

void drcbe_la64::mov_float_param_param(lagoon_assembler_t &a, uint32_t regsize, const be_parameter &dst, const be_parameter &src) const
{
	assert(!src.is_immediate());
	assert(!dst.is_immediate());

	if (dst.is_float_register())
	{
		mov_float_reg_param(a, regsize, dst.get_register_float(regsize), src);
	}
	else if (dst.is_memory())
	{
		if (src.is_float_register())
		{
			mov_float_param_reg(a, regsize, dst, src.get_register_float(regsize));
		}
		else if (src.is_memory())
		{
			emit_float_ldr_mem(a, TEMPF_REG1, src.memory(), regsize);
			emit_float_str_mem(a, TEMPF_REG1, dst.memory(), regsize);
		}
	}
}


void drcbe_la64::emit_memaccess_setup(lagoon_assembler_t &a, const be_parameter &addrp, const memory_accessors &accessors, const address_space::specific_access_info::side &side) const
{
	la_gpr_t const addrreg = (accessors.no_mask || accessors.mask_simple) ? REG_PARAM2 : FUNC_SCRATCH_REG;
	mov_reg_param(a, 4, addrreg, addrp);
	load_address(a, MEM_SCRATCH_REG, uintptr_t(side.dispatch));

	if (accessors.high_bits && !accessors.mask_high_bits)
		la_bstrpick_d(&a, SCRATCH_REG1, addrreg, accessors.specific.low_bits + accessors.high_bits - 1, accessors.specific.low_bits);

	if (!accessors.no_mask)
	{
		if (accessors.mask_simple && (accessors.address_mask < 0x1000))
		{
			la_andi(&a, REG_PARAM2, addrreg, uint32_t(accessors.address_mask));
		}
		else
		{
			load_imm64(a, SCRATCH_REG2, accessors.address_mask);
			la_and(&a, REG_PARAM2, addrreg, SCRATCH_REG2);
		}
	}

	if (!accessors.high_bits)
	{
		la_ld_d(&a, REG_PARAM1, MEM_SCRATCH_REG, 0);
	}
	else if (!accessors.mask_high_bits)
	{
		la_slli_d(&a, SCRATCH_REG1, SCRATCH_REG1, 3);
		la_add_d(&a, MEM_SCRATCH_REG, MEM_SCRATCH_REG, SCRATCH_REG1);
		la_ld_d(&a, REG_PARAM1, MEM_SCRATCH_REG, 0);
	}
	else
	{
		la_srli_d(&a, SCRATCH_REG1, REG_PARAM2, accessors.specific.low_bits);
		la_slli_d(&a, SCRATCH_REG1, SCRATCH_REG1, 3);
		la_add_d(&a, MEM_SCRATCH_REG, MEM_SCRATCH_REG, SCRATCH_REG1);
		la_ld_d(&a, REG_PARAM1, MEM_SCRATCH_REG, 0);
	}

	if (side.displacement)
	{
		if ((side.displacement >= -2048) && (side.displacement <= 2047))
			la_addi_d(&a, REG_PARAM1, REG_PARAM1, int32_t(side.displacement));
		else
		{
			load_imm64(a, SCRATCH_REG1, uint64_t(side.displacement));
			la_add_d(&a, REG_PARAM1, REG_PARAM1, SCRATCH_REG1);
		}
	}
}

void drcbe_la64::emit_narrow_memaccess_setup(lagoon_assembler_t &a, const be_parameter &addrp, const parameter &spacesizep, const memory_accessors &accessors, const address_space::specific_access_info::side &side) const
{
	address_space &space = *m_space[spacesizep.space()];
	la_gpr_t const addrreg = (accessors.no_mask || accessors.mask_simple) ? REG_PARAM2 : FUNC_SCRATCH_REG;
	mov_reg_param(a, 4, addrreg, addrp);
	load_address(a, MEM_SCRATCH_REG, uintptr_t(side.dispatch));

	// compute the data/shift offset within the native word
	int const shift = space.addr_shift() - 3;
	uint32_t const shiftmask = (accessors.specific.native_bytes - (1 << spacesizep.size())) << 3;
	if (space.endianness() != ENDIANNESS_LITTLE)
	{
		bool const smallshift = (shift <= 0) && (shift >= -3);
		if (!smallshift)
		{
			if (shift < 0)
				la_slli_w(&a, SCRATCH_REG1, addrreg, -shift);
			else
				la_srli_w(&a, SCRATCH_REG1, addrreg, shift);
		}
		load_imm32(a, FLAGS_REG, shiftmask);
		if (smallshift)
		{
			if (shift < 0)
			{
				la_slli_d(&a, SCRATCH_REG2, addrreg, -shift);
				la_andn(&a, FLAGS_REG, FLAGS_REG, SCRATCH_REG2);
			}
			else
			{
				la_andn(&a, FLAGS_REG, FLAGS_REG, addrreg);
			}
		}
		else
		{
			la_andn(&a, FLAGS_REG, FLAGS_REG, SCRATCH_REG1);
		}
	}
	else
	{
		if (shift == 0)
		{
			la_andi(&a, FLAGS_REG, addrreg, int32_t(shiftmask));
		}
		else
		{
			if (shift < 0)
				la_slli_w(&a, FLAGS_REG, addrreg, -shift);
			else
				la_srli_w(&a, FLAGS_REG, addrreg, shift);
			la_andi(&a, FLAGS_REG, FLAGS_REG, int32_t(shiftmask));
		}
	}

	// if the high bits aren't affected by the global mask, extract them early
	if (accessors.high_bits && !accessors.mask_high_bits)
		la_bstrpick_d(&a, SCRATCH_REG1, addrreg, accessors.specific.low_bits + accessors.high_bits - 1, accessors.specific.low_bits);

	if (!accessors.no_mask)
	{
		if (accessors.mask_simple && (accessors.address_mask < 0x1000))
		{
			la_andi(&a, REG_PARAM2, addrreg, uint32_t(accessors.address_mask));
		}
		else
		{
			load_imm64(a, SCRATCH_REG2, accessors.address_mask);
			la_and(&a, REG_PARAM2, addrreg, SCRATCH_REG2);
		}
	}

	// if the high address bits aren't affected by the global mask, load the dispatch entry now
	if (!accessors.high_bits)
	{
		la_ld_d(&a, REG_PARAM1, MEM_SCRATCH_REG, 0);
	}
	else if (!accessors.mask_high_bits)
	{
		la_slli_d(&a, SCRATCH_REG1, SCRATCH_REG1, 3);
		la_add_d(&a, MEM_SCRATCH_REG, MEM_SCRATCH_REG, SCRATCH_REG1);
		la_ld_d(&a, REG_PARAM1, MEM_SCRATCH_REG, 0);
	}
	else
	{
		la_srli_d(&a, SCRATCH_REG1, REG_PARAM2, accessors.specific.low_bits);
		la_slli_d(&a, SCRATCH_REG1, SCRATCH_REG1, 3);
		la_add_d(&a, MEM_SCRATCH_REG, MEM_SCRATCH_REG, SCRATCH_REG1);
		la_ld_d(&a, REG_PARAM1, MEM_SCRATCH_REG, 0);
	}

	if (side.displacement)
	{
		if ((side.displacement >= -2048) && (side.displacement <= 2047))
			la_addi_d(&a, REG_PARAM1, REG_PARAM1, int32_t(side.displacement));
		else
		{
			load_imm64(a, SCRATCH_REG1, uint64_t(side.displacement));
			la_add_d(&a, REG_PARAM1, REG_PARAM1, SCRATCH_REG1);
		}
	}
}

void drcbe_la64::emit_narrow_memread(lagoon_assembler_t &a, const be_parameter &addrp, const parameter &spacesizep, const memory_accessors &accessors) const
{
	// mask is in REG_PARAM3
	emit_narrow_memaccess_setup(a, addrp, spacesizep, accessors, accessors.specific.read);

	la_sll_d(&a, REG_PARAM3, REG_PARAM3, FLAGS_REG);

	emit_specific_call(a, accessors.specific.read);

	if (accessors.specific.native_bytes <= 4)
		la_srl_w(&a, REG_PARAM1, REG_PARAM1, FLAGS_REG);
	else
		la_srl_d(&a, REG_PARAM1, REG_PARAM1, FLAGS_REG);

	la_move(&a, FLAGS_REG, LA_ZERO);
}

void drcbe_la64::emit_narrow_memwrite(lagoon_assembler_t &a, const be_parameter &addrp, const parameter &spacesizep, const memory_accessors &accessors) const
{
	// data is in REG_PARAM3 and mask is in REG_PARAM4
	emit_narrow_memaccess_setup(a, addrp, spacesizep, accessors, accessors.specific.write);

	la_sll_d(&a, REG_PARAM3, REG_PARAM3, FLAGS_REG);
	la_sll_d(&a, REG_PARAM4, REG_PARAM4, FLAGS_REG);

	emit_specific_call(a, accessors.specific.write);
}

void drcbe_la64::emit_specific_call(lagoon_assembler_t &a, const address_space::specific_access_info::side &side) const
{
	if (side.is_virtual)
	{
		la_ld_d(&a, SCRATCH_REG2, REG_PARAM1, 0);
		if (side.function < 0x800)
			la_addi_d(&a, SCRATCH_REG2, SCRATCH_REG2, int32_t(side.function));
		else
		{
			load_imm64(a, SCRATCH_REG1, side.function);
			la_add_d(&a, SCRATCH_REG2, SCRATCH_REG2, SCRATCH_REG1);
		}
		la_ld_d(&a, SCRATCH_REG2, SCRATCH_REG2, 0);
		la_jirl(&a, LA_RA, SCRATCH_REG2, 0);
	}
	else
	{
		call_helper_addr(a, side.function);
	}
}


drcbe_la64::drcbe_la64(drcuml_state &drcuml, device_t &device, drc_cache &cache, uint32_t flags, int modes, int addrbits, int ignorebits)
	: drcbe_interface(drcuml, cache, device)
	, m_hash(cache, modes, addrbits, ignorebits, drcuml.max_sequence_length(), std::align_val_t(1 << 12), std::align_val_t(1 << 12))
	, m_map(cache, 0xaaaaaaaa5555)
	, m_log_native(nullptr)
	, m_invariant_block(false)
	, m_entry(nullptr)
	, m_exit(nullptr)
	, m_nocode(nullptr)
	, m_endofblock(nullptr)
	, m_baseptr(cache.near() + 0x100)
	, m_near(*cache.alloc_near<near_state>())
{
	memset(&m_near, 0, sizeof(m_near));
	m_near.single1 = 1.0F;
	m_near.double1 = 1.0;

	if (device.machine().options().drc_log_native())
	{
		std::string tag = device.tag();
		for (auto &ch : tag)
		{
			if (':' == ch)
				ch = '_';
		}
		std::ostringstream str;
		str.imbue(std::locale::classic());
		str << "drcbela64_" << device.shortname();
		if ('_' != tag[0])
			str << '_';
		str << tag << ".asm";
		m_log_native = fopen(std::move(str).str().c_str(), "w");
	}

	m_drcmap_get_value.set(m_map, &drc_map_variables::get_value);
	if (!m_drcmap_get_value)
		throw emu_fatalerror("Error resolving map variable get value function!\n");

	m_memory_accessors.resize(m_space.size());
	for (int space = 0; m_space.size() > space; ++space)
	{
		if (m_space[space])
		{
			auto &accessors = m_memory_accessors[space];
			accessors.resolved.set(*m_space[space]);
			accessors.specific = m_space[space]->specific_accessors();
			accessors.address_mask = m_space[space]->addrmask() & make_bitmask<offs_t>(accessors.specific.address_width) & ~make_bitmask<offs_t>(accessors.specific.native_mask_bits);
			offs_t const shiftedmask = accessors.address_mask >> accessors.specific.low_bits;
			offs_t const nomask = ~offs_t(0);
			accessors.high_bits = std::bit_width(shiftedmask);
			accessors.no_mask = nomask == accessors.address_mask;
			accessors.mask_simple = !accessors.no_mask && (accessors.address_mask < 0x1000);
			accessors.mask_high_bits = (shiftedmask & (shiftedmask + 1)) != 0;
		}
	}

	uint32_t const reserve = 4096;
	drccodeptr *cachetop = m_cache.begin_codegen_invariant(reserve);
	if (!cachetop)
		throw emu_fatalerror("drcbe_la64(%s): unable to allocate invariant code\n", device.tag());

	uint8_t *dst = (uint8_t *)((uintptr_t(*cachetop) + 15) & ~uintptr_t(15));
	lagoon_assembler_t as;
	la_init_assembler(&as, dst, reserve - (dst - *cachetop));

	emit_invariant_code(as, dst);

	if (m_log_native)
	{
		fprintf(m_log_native, "; entry=%p exit=%p nocode=%p endofblock=%p\n",
				(void *)m_entry, (void *)m_exit, (void *)m_nocode, (void *)m_endofblock);
		log_range(dst, as.cursor, "invariant code");
	}

	*cachetop = (drccodeptr)as.cursor;
	m_cache.end_codegen();

	m_hash.set_default_codeptr(m_nocode);
}

drcbe_la64::~drcbe_la64()
{
	if (m_log_native)
		fclose(m_log_native);
}

void drcbe_la64::emit_invariant_code(lagoon_assembler_t &a, uint8_t *dst)
{
	// entry point
	m_entry = (la64_entry_point_func)dst;

	la_addi_d(&a, LA_SP, LA_SP, -TOP_FRAME_SIZE);
	la_st_d(&a, LA_RA, LA_SP, TOP_FRAME_RA);
	la_st_d(&a, LA_FP, LA_SP, TOP_FRAME_FP);
	la_st_d(&a, TOP_SP_REG, LA_SP, TOP_FRAME_TOP_SP);
	for (int reg = 0; reg < 9; reg++)
		la_st_d(&a, la_gpr_t(LA_S0 + reg), LA_SP, TOP_FRAME_S0 + (8 * reg));
	for (int reg = 0; reg < 8; reg++)
		la_fst_d(&a, la_fpr_t(LA_FS0 + reg), LA_SP, TOP_FRAME_FS0 + (8 * reg));

	// remember this invocation's top-level frame for EXIT and RECOVER
	la_move(&a, TOP_SP_REG, LA_SP);

	// save the incoming FCSR and establish the initial rounding mode
	la_movfcsr2gr(&a, TEMP_REG1, LA_FCSR0);
	load_imm64(a, BASE_REG, uintptr_t(m_baseptr));
	emit_str_state_d(a, TEMP_REG1, &m_near.saved_fcsr);

	// remember the host's nominal rounding mode for helper calls
	la_srli_d(&a, TEMP_REG2, TEMP_REG1, 8);
	la_andi(&a, TEMP_REG2, TEMP_REG2, 3);
	la_xori(&a, TEMP_REG2, TEMP_REG2, 1);
	emit_str_state_b(a, TEMP_REG2, &m_near.nominal_fmod);

	emit_ldr_state_b(a, TEMP_REG3, &m_state.fmod);
	la_xor(&a, TEMP_REG3, TEMP_REG3, TEMP_REG2);
	la_sltu(&a, TEMP_REG3, LA_ZERO, TEMP_REG3);
	emit_str_state_b(a, TEMP_REG3, &m_near.fmod_changed);

	la_move(&a, FLAGS_REG, LA_ZERO);
	emit_sync_fcsr(a);

	// call the generated entry point (entry in a0)
	la_jirl(&a, LA_RA, REG_PARAM1, 0);

	// exit point
	m_exit = a.cursor;
	load_address(a, TEMP_REG1, uintptr_t(&m_near.saved_fcsr));
	la_ld_d(&a, TEMP_REG1, TEMP_REG1, 0);
	la_movgr2fcsr(&a, LA_FCSR0, TEMP_REG1);

	// discard any outstanding generated subroutines and return to the top-level frame
	la_move(&a, LA_SP, TOP_SP_REG);

	for (int reg = 0; reg < 8; reg++)
		la_fld_d(&a, la_fpr_t(LA_FS0 + reg), LA_SP, TOP_FRAME_FS0 + (8 * reg));
	for (int reg = 8; reg >= 0; reg--)
		la_ld_d(&a, la_gpr_t(LA_S0 + reg), LA_SP, TOP_FRAME_S0 + (8 * reg));
	la_ld_d(&a, TOP_SP_REG, LA_SP, TOP_FRAME_TOP_SP);
	la_ld_d(&a, LA_RA, LA_SP, TOP_FRAME_RA);
	la_ld_d(&a, LA_FP, LA_SP, TOP_FRAME_FP);
	la_addi_d(&a, LA_SP, LA_SP, TOP_FRAME_SIZE);
	la_ret(&a);

	// no code point
	m_nocode = a.cursor;
	la_jr(&a, REG_PARAM1);

	// end-of-block point
	m_endofblock = a.cursor;
	{
		auto const [entrypoint, adjusted] = util::resolve_member_function(&drcbe_la64::end_of_block, *this);
		load_imm64(a, REG_PARAM1, adjusted);
		call_helper_addr(a, uintptr_t(entrypoint));
	}
}

void drcbe_la64::log_range(const uint8_t *start, const uint8_t *end, const char *comment)
{
	if (!m_log_native)
		return;

	for (const uint8_t *ptr = start; ptr < end; ptr += 4)
	{
		uint32_t word;
		memcpy(&word, ptr, sizeof(word));
		lagoon_insn_t insn;
		char text[128];
		la_disasm_one(word, &insn);
		la_insn_to_str(&insn, text, sizeof(text));
		fprintf(m_log_native, "%p: %08x  %-40s", (const void *)ptr, word, text);
		if (ptr == start && comment)
			fprintf(m_log_native, "  ; %s", comment);
		fputc('\n', m_log_native);
	}
}

