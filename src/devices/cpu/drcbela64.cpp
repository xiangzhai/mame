void drcbe_la64::generate(drcuml_block &block, const instruction *instlist, uint32_t numinst)
{
	if (!m_debug_cpu_instruction_hook && (m_device.machine().debug_flags & DEBUG_FLAG_ENABLED) && m_device.debug())
	{
		m_debug_cpu_instruction_hook.set(*m_device.debug(), &device_debug::instruction_hook);
		if (!m_debug_cpu_instruction_hook)
			throw emu_fatalerror("Error resolving debugger instruction hook member function!\n");
	}

	m_hash.block_begin(block, instlist, numinst);
	m_map.block_begin(block);
	m_invariant_block = block.invariant();

	// release any labels left over from a previously aborted block
	{
		lagoon_assembler_t dummy;
		for (auto &entry : m_labels)
			la_label_free(&dummy, &entry.second);
		m_labels.clear();
	}

	uint32_t const reserve = uint32_t(numinst * RESERVE_PER_INSTRUCTION + MAX_OP_BYTES);
	drccodeptr *cachetop = block.invariant()
			? m_cache.begin_codegen_invariant(reserve)
			: m_cache.begin_codegen(reserve);
	if (!cachetop)
		block.abort();

	uint8_t *base = (uint8_t *)((uintptr_t(*cachetop) + 15) & ~uintptr_t(15));
	size_t capacity = reserve - (base - *cachetop);

	lagoon_assembler_t a;
	la_init_assembler(&a, base, capacity);

	std::vector<std::tuple<uint8_t *, uint8_t *, std::string>> log_entries;
	std::vector<uint8_t> const flag_live_in = analyze_flag_liveness(instlist, numinst);

	for (uint32_t inum = 0; inum < numinst; inum++)
	{
		uint32_t const instnum = inum;
		const instruction &inst = instlist[inum];

		if (la_get_remaining_buffer_size(&a) < MAX_OP_BYTES)
		{
			*cachetop = (drccodeptr)a.cursor;
			m_cache.end_codegen();
			lagoon_assembler_t dummy;
			for (auto &entry : m_labels)
				la_label_free(&dummy, &entry.second);
			m_labels.clear();
			block.abort();
		}

		uint8_t *before = a.cursor;
		uint32_t consumed = 1;
		if (!try_fuse_cmp_branch(a, instlist, numinst, inum, flag_live_in, consumed))
			generate_one(a, inst);
		inum += consumed - 1;

		if (m_log_native && (a.cursor != before))
		{
			std::string dasm = inst.disasm(&m_drcuml);
			if (consumed > 1)
			{
				dasm += " ; fused with ";
				for (uint32_t index = 1; index < consumed; index++)
				{
					if (index > 1)
						dasm += ", ";
					dasm += instlist[instnum + index].disasm(&m_drcuml);
				}
			}
			log_entries.emplace_back(before, a.cursor, std::move(dasm));
		}
	}

	// catch falling off the end of a block
	uint8_t *before = a.cursor;
	load_address(a, TEMP_REG1, uintptr_t(m_endofblock));
	la_jr(&a, TEMP_REG1);
	if (m_log_native && (a.cursor != before))
		log_entries.emplace_back(before, a.cursor, "end of block");

	// all labels are bound now, so the logged instructions reflect any patched branches
	for (auto const &entry : log_entries)
		log_range(std::get<0>(entry), std::get<1>(entry), std::get<2>(entry).c_str());

	*cachetop = (drccodeptr)a.cursor;
	m_cache.end_codegen();

	{
		lagoon_assembler_t dummy;
		for (auto &entry : m_labels)
			la_label_free(&dummy, &entry.second);
		m_labels.clear();
	}

	m_hash.block_end(block);
	m_map.block_end(block);
}

