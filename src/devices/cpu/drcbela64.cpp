/***************************************************************************

    drcbela64.cpp

    LoongArch64 back-end for the universal machine language.

    The code generator uses the lagoon assembler library.  Code is emitted
    directly into the DRC cache so that PC-relative pseudo-instructions
    (la.local/la.global) resolve against the final address.

Register use:

r0      zero
r1      ra
r3      sp
r4-r11  a0-a7       parameters/scratch
r12-r20 t0-t8       temporaries/scratch
r22     fp          near cache base pointer
r23-r30 s0-s7       UML registers I0-I7
r31     s8          software emulated flags
f24-f31 fs0-fs7     UML registers F0-F7

Software flags layout (matches uml::FLAG_BIT_*):

bit 0 = C, bit 1 = V, bit 2 = Z, bit 3 = S, bit 4 = U

***************************************************************************/

